"""Research readiness gate — evaluate knowledge completeness before research.

Phase 10 of the Scientific Knowledge Build-up roadmap.

Before autonomous execution, evaluate:
  - Knowledge completeness
  - Knowledge confidence
  - Missing datasets
  - Missing references
  - Missing implementations
  - Unknown assumptions

Generate a Research Readiness Report.

Example:
  Knowledge completeness: 94%
  Confidence: High
  Missing datasets: 1
  Unknown notebook: 2
  Recommendation: Ready for autonomous research

User must approve.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass, field
from datetime import datetime, timezone
from enum import Enum
from typing import Any

logger = logging.getLogger(__name__)


# ── Readiness Status ──────────────────────────────────────────────────────


class ReadinessLevel(str, Enum):
    """Overall readiness level for autonomous research."""

    READY = "ready"               # Knowledge is complete enough
    PARTIALLY_READY = "partially_ready"  # Some gaps but can proceed
    NOT_READY = "not_ready"       # Too many gaps
    BLOCKED = "blocked"           # Critical blocker (e.g., no knowledge at all)


class ConfidenceLevel(str, Enum):
    """Qualitative confidence level."""

    HIGH = "high"
    MEDIUM = "medium"
    LOW = "low"
    UNKNOWN = "unknown"


class IssueSeverity(str, Enum):
    """Severity of a readiness issue."""

    CRITICAL = "critical"     # Must fix before research
    WARNING = "warning"        # Should fix but can proceed
    INFO = "info"              # Informational only


# ── Readiness Issue ────────────────────────────────────────────────────────


@dataclass
class ReadinessIssue:
    """A single issue found during readiness evaluation."""

    issue_id: str = ""
    severity: IssueSeverity = IssueSeverity.INFO
    category: str = ""          # missing_dataset, missing_reference, etc.
    description: str = ""
    affected_artifacts: list[str] = field(default_factory=list)
    recommendation: str = ""    # How to fix it

    def to_dict(self) -> dict[str, Any]:
        return {
            "issue_id": self.issue_id,
            "severity": self.severity.value,
            "category": self.category,
            "description": self.description,
            "affected_artifacts": self.affected_artifacts,
            "recommendation": self.recommendation,
        }


# ── Research Readiness Report ─────────────────────────────────────────────


@dataclass
class ResearchReadinessReport:
    """Complete research readiness report for a project.

    This report is generated by the Research Readiness Gate (Phase 10)
    and must be approved by the user before autonomous research begins.
    """

    project_id: str = ""
    generated_at: str = ""

    # Overall scores
    knowledge_completeness: float = 0.0      # 0.0–1.0
    knowledge_confidence: float = 0.0        # 0.0–1.0
    coverage_score: float = 0.0              # 0.0–1.0

    # Qualitative assessments
    readiness_level: ReadinessLevel = ReadinessLevel.NOT_READY
    confidence_level: ConfidenceLevel = ConfidenceLevel.UNKNOWN

    # Coverage by type
    artifact_counts: dict[str, int] = field(default_factory=dict)
    complete_counts: dict[str, int] = field(default_factory=dict)
    partial_counts: dict[str, int] = field(default_factory=dict)
    missing_counts: dict[str, int] = field(default_factory=dict)

    # Issues
    issues: list[ReadinessIssue] = field(default_factory=list)
    critical_issue_count: int = 0
    warning_issue_count: int = 0
    info_issue_count: int = 0

    # Missing items
    missing_datasets: list[str] = field(default_factory=list)
    missing_references: list[str] = field(default_factory=list)
    missing_implementations: list[str] = field(default_factory=list)
    unknown_assumptions: list[str] = field(default_factory=list)
    incomplete_parsing: list[str] = field(default_factory=list)
    broken_references: list[str] = field(default_factory=list)
    unknown_formats: list[str] = field(default_factory=list)

    # Recommendations
    recommendation: str = ""
    next_steps: list[str] = field(default_factory=list)

    # User approval
    user_approved: bool = False
    approved_at: str = ""
    approved_by: str = ""

    def to_dict(self) -> dict[str, Any]:
        return {
            "project_id": self.project_id,
            "generated_at": self.generated_at,
            "knowledge_completeness": self.knowledge_completeness,
            "knowledge_confidence": self.knowledge_confidence,
            "coverage_score": self.coverage_score,
            "readiness_level": self.readiness_level.value,
            "confidence_level": self.confidence_level.value,
            "artifact_counts": self.artifact_counts,
            "complete_counts": self.complete_counts,
            "partial_counts": self.partial_counts,
            "missing_counts": self.missing_counts,
            "issues": [i.to_dict() for i in self.issues],
            "critical_issue_count": self.critical_issue_count,
            "warning_issue_count": self.warning_issue_count,
            "info_issue_count": self.info_issue_count,
            "missing_datasets": self.missing_datasets,
            "missing_references": self.missing_references,
            "missing_implementations": self.missing_implementations,
            "unknown_assumptions": self.unknown_assumptions,
            "incomplete_parsing": self.incomplete_parsing,
            "broken_references": self.broken_references,
            "unknown_formats": self.unknown_formats,
            "recommendation": self.recommendation,
            "next_steps": self.next_steps,
            "user_approved": self.user_approved,
            "approved_at": self.approved_at,
            "approved_by": self.approved_by,
        }


# ── Research Readiness Gate ───────────────────────────────────────────────


class ResearchReadinessGate:
    """Evaluate research readiness based on knowledge completeness.

    Usage:
        gate = ResearchReadinessGate()
        report = gate.evaluate(project_id, coverage_dashboard, knowledge_store)
    """

    def evaluate(
        self,
        project_id: str,
        coverage_dashboard: Any,
        memory_store: Any = None,
    ) -> ResearchReadinessReport:
        """Evaluate research readiness for a project.

        Args:
            project_id: The project ID
            coverage_dashboard: CoverageDashboard from Phase 7
            memory_store: ScientificMemoryStore from Phase 9 (optional)

        Returns:
            A ``ResearchReadinessReport`` with readiness information.
        """
        report = ResearchReadinessReport(
            project_id=project_id,
            generated_at=datetime.now(timezone.utc).isoformat(),
        )

        # Extract coverage data from dashboard
        if hasattr(coverage_dashboard, "to_dict"):
            dashboard_data = coverage_dashboard.to_dict()
        else:
            dashboard_data = coverage_dashboard

        # Copy coverage scores
        report.coverage_score = dashboard_data.get("coverage_score", 0.0)
        report.knowledge_completeness = dashboard_data.get("completeness_score", 0.0)
        report.knowledge_confidence = dashboard_data.get("confidence_score", 0.0)

        # Copy artifact counts
        report.artifact_counts = dashboard_data.get("type_counts", {})
        report.complete_counts = dashboard_data.get("type_complete", {})
        report.partial_counts = dashboard_data.get("type_partial", {})
        report.missing_counts = dashboard_data.get("type_missing", {})

        # Copy issues
        report.missing_datasets = dashboard_data.get("missing_datasets", [])
        report.missing_references = dashboard_data.get("missing_references", [])
        report.missing_implementations = dashboard_data.get("missing_implementations", [])
        report.unknown_assumptions = dashboard_data.get("unknown_assumptions", [])
        report.incomplete_parsing = dashboard_data.get("incomplete_parsing", [])
        report.broken_references = dashboard_data.get("broken_references", [])
        report.unknown_formats = dashboard_data.get("unknown_formats", [])

        # Generate issues from coverage gaps
        self._generate_issues(report, dashboard_data)

        # Determine readiness level
        self._determine_readiness_level(report)

        # Determine confidence level
        self._determine_confidence_level(report)

        # Generate recommendation
        self._generate_recommendation(report)

        return report

    def _generate_issues(
        self,
        report: ResearchReadinessReport,
        dashboard_data: dict[str, Any],
    ) -> None:
        """Generate readiness issues from coverage gaps."""
        issue_counter = 0

        # Check for missing datasets
        if report.missing_datasets:
            issue_counter += 1
            report.issues.append(ReadinessIssue(
                issue_id=f"issue-{issue_counter}",
                severity=IssueSeverity.WARNING,
                category="missing_datasets",
                description=f"{len(report.missing_datasets)} missing dataset(s)",
                affected_artifacts=report.missing_datasets,
                recommendation="Upload the missing datasets before starting research",
            ))

        # Check for missing references
        if report.missing_references:
            issue_counter += 1
            report.issues.append(ReadinessIssue(
                issue_id=f"issue-{issue_counter}",
                severity=IssueSeverity.WARNING,
                category="missing_references",
                description=f"{len(report.missing_references)} missing reference(s)",
                affected_artifacts=report.missing_references,
                recommendation="Add the missing references to the knowledge base",
            ))

        # Check for missing implementations
        if report.missing_implementations:
            issue_counter += 1
            report.issues.append(ReadinessIssue(
                issue_id=f"issue-{issue_counter}",
                severity=IssueSeverity.WARNING,
                category="missing_implementations",
                description=f"{len(report.missing_implementations)} missing implementation(s)",
                affected_artifacts=report.missing_implementations,
                recommendation="Implement the missing algorithms or code",
            ))

        # Check for unknown assumptions
        if report.unknown_assumptions:
            issue_counter += 1
            report.issues.append(ReadinessIssue(
                issue_id=f"issue-{issue_counter}",
                severity=IssueSeverity.CRITICAL,
                category="unknown_assumptions",
                description=f"{len(report.unknown_assumptions)} unverified assumption(s)",
                affected_artifacts=report.unknown_assumptions,
                recommendation="Verify or explicitly accept all assumptions before research",
            ))

        # Check for incomplete parsing
        if report.incomplete_parsing:
            issue_counter += 1
            report.issues.append(ReadinessIssue(
                issue_id=f"issue-{issue_counter}",
                severity=IssueSeverity.WARNING,
                category="incomplete_parsing",
                description=f"{len(report.incomplete_parsing)} artifact(s) with incomplete parsing",
                affected_artifacts=report.incomplete_parsing,
                recommendation="Re-ingest the affected artifacts",
            ))

        # Check for broken references
        if report.broken_references:
            issue_counter += 1
            report.issues.append(ReadinessIssue(
                issue_id=f"issue-{issue_counter}",
                severity=IssueSeverity.WARNING,
                category="broken_references",
                description=f"{len(report.broken_references)} broken reference(s)",
                affected_artifacts=report.broken_references,
                recommendation="Fix the broken references in the knowledge graph",
            ))

        # Check for unknown formats
        if report.unknown_formats:
            issue_counter += 1
            report.issues.append(ReadinessIssue(
                issue_id=f"issue-{issue_counter}",
                severity=IssueSeverity.INFO,
                category="unknown_formats",
                description=f"{len(report.unknown_formats)} artifact(s) with unknown format",
                affected_artifacts=report.unknown_formats,
                recommendation="Consider adding support for the unknown formats",
            ))

        # Count issues by severity
        report.critical_issue_count = sum(
            1 for i in report.issues if i.severity == IssueSeverity.CRITICAL
        )
        report.warning_issue_count = sum(
            1 for i in report.issues if i.severity == IssueSeverity.WARNING
        )
        report.info_issue_count = sum(
            1 for i in report.issues if i.severity == IssueSeverity.INFO
        )

    def _determine_readiness_level(self, report: ResearchReadinessReport) -> None:
        """Determine the overall readiness level."""
        # Blocked: no knowledge at all
        if report.knowledge_completeness == 0.0 and not report.artifact_counts:
            report.readiness_level = ReadinessLevel.BLOCKED
            return

        # Not ready: critical issues or very low completeness
        if report.critical_issue_count > 0 or report.knowledge_completeness < 0.3:
            report.readiness_level = ReadinessLevel.NOT_READY
            return

        # Partially ready: some warnings or moderate completeness
        if report.warning_issue_count > 0 or report.knowledge_completeness < 0.7:
            report.readiness_level = ReadinessLevel.PARTIALLY_READY
            return

        # Ready: high completeness, no critical issues
        report.readiness_level = ReadinessLevel.READY

    def _determine_confidence_level(self, report: ResearchReadinessReport) -> None:
        """Determine the qualitative confidence level."""
        if report.knowledge_confidence >= 0.8:
            report.confidence_level = ConfidenceLevel.HIGH
        elif report.knowledge_confidence >= 0.5:
            report.confidence_level = ConfidenceLevel.MEDIUM
        elif report.knowledge_confidence > 0.0:
            report.confidence_level = ConfidenceLevel.LOW
        else:
            report.confidence_level = ConfidenceLevel.UNKNOWN

    def _generate_recommendation(self, report: ResearchReadinessReport) -> None:
        """Generate the recommendation and next steps."""
        if report.readiness_level == ReadinessLevel.READY:
            report.recommendation = "Ready for autonomous research"
            report.next_steps = [
                "User approves the research readiness report",
                "Autonomous research planner generates research objectives",
                "Autonomous research loop begins",
            ]
        elif report.readiness_level == ReadinessLevel.PARTIALLY_READY:
            report.recommendation = "Partially ready — proceed with caution"
            report.next_steps = [
                "Review the warnings and issues",
                "Fix the critical issues before proceeding",
                "Consider whether the knowledge gaps are acceptable",
                "User approves the research readiness report",
            ]
        elif report.readiness_level == ReadinessLevel.NOT_READY:
            report.recommendation = "Not ready — knowledge base needs improvement"
            report.next_steps = [
                "Fix all critical issues",
                "Improve knowledge completeness (currently "
                f"{report.knowledge_completeness:.0%})",
                "Re-run the readiness gate",
                "User approves the research readiness report",
            ]
        elif report.readiness_level == ReadinessLevel.BLOCKED:
            report.recommendation = "Blocked — no knowledge base found"
            report.next_steps = [
                "Upload papers, code, notebooks, and datasets",
                "Run the unified knowledge ingestion pipeline",
                "Re-run the readiness gate",
            ]


# ── Convenience Function ────────────────────────────────────────────────────


def evaluate_readiness(
    project_id: str,
    coverage_dashboard: Any,
    memory_store: Any = None,
) -> ResearchReadinessReport:
    """Evaluate research readiness for a project (convenience function).

    Args:
        project_id: The project ID
        coverage_dashboard: CoverageDashboard from Phase 7
        memory_store: ScientificMemoryStore from Phase 9 (optional)

    Returns:
        A ``ResearchReadinessReport`` with readiness information.
    """
    gate = ResearchReadinessGate()
    return gate.evaluate(project_id, coverage_dashboard, memory_store)
