"""Render the bundled-ontology seed migration (ADR-081 KN-2, slice KN-S7).

The seed migration (``<next>_knowledge_terms_seed.sql``) is generated from
the package data by ``python -m umrs.knowledge.ontologies`` and checked in;
a test asserts the checked-in file equals :func:`render_seed_sql` of the
bundled documents, so the YAML stays the one source.

Output contract of :func:`render_seed_sql` (deterministic; every statement
on one line ending ``;`` and a newline):

1. :data:`HEADER` (comment lines, each ending with a newline).
2. One ``INSERT INTO knowledge_ontologies (record_id, ontology_id, version,
   entity_types, relation_types, transitive_relations, description,
   owner_id, project_id, iri_base, prefixes, imports, profile) VALUES (...)
   ON CONFLICT DO NOTHING;`` per document, sorted by ref. ``record_id`` is
   ``bundled_record_id(ref)``; ``entity_types`` / ``relation_types`` /
   ``transitive_relations`` are JSON lists of the doc's own class /
   relation / transitive-relation term ids, sorted; ``owner_id`` is
   ``'system'``; ``project_id`` is NULL; ``imports`` is the JSON list of the
   doc's imports in declared order.
3. One ``INSERT INTO knowledge_terms (<TERM_COLUMNS joined by ", ">) VALUES
   (...) ON CONFLICT (term_id) DO NOTHING;`` per term of all documents,
   sorted by term_id. A term id defined by two documents raises ValueError.
   Column values in :data:`TERM_COLUMNS` order from the TermSpec fields
   (``synonyms`` and ``mappings`` as jsonb; ``parents``, ``domain_classes``,
   ``range_classes``, ``aliases``, ``required_on`` as text[]).
4. One ``INSERT INTO knowledge_term_closure (ancestor, descendant, depth)
   VALUES (...) ON CONFLICT DO NOTHING;`` per closure entry, sorted by
   (ancestor, descendant).
5. One ``INSERT INTO knowledge_ontology_terms (record_id, term_id, via)
   VALUES (...) ON CONFLICT DO NOTHING;`` per ``admitted[ref]`` entry, sorted
   by (record_id, term_id).

Values are separated by ``", "``. Literals: :func:`sql_text`,
:func:`sql_text_array`, :func:`sql_jsonb`, :func:`sql_bool`.
"""

