class PrefixedSentenceTransformerEmbeddings(SentenceTransformerEmbeddings):
    """SentenceTransformerEmbeddings with automatic E5 query/document prefixes.

    E5 models require 'query: ' prefix for search queries and 'passage: '
    prefix for documents.  This wrapper applies the correct prefix
    transparently based on the model name.
    """

    def embed_query(self, text: str) -> List[float]:
        text = add_query_prefix(text, self.model_name)
        return super().embed_query(text)

    def embed_documents(self, texts: List[str]) -> List[List[float]]:
        texts = add_document_prefix(texts, self.model_name)
        return super().embed_documents(texts)


def _detect_embedding_model_from_config(
    db_model_store: Dict[str, Dict[str, Any]],
) -> Optional[str]:
    """Extract the embedding model name from the first text-modality entry."""
    for entry in db_model_store.values():
        if entry.get("modality_name") == "text" and entry.get("store_embeddings_flag"):
            model = entry.get("model")
            if model is None:
                continue
            # EmbeddingModel object (from load_model)
            if hasattr(model, "model_name"):
                return model.model_name
            # Raw config dict (fallback)
            if isinstance(model, dict) and "model_name" in model:
                return model["model_name"]
    return None


DB_MODEL_STORE: Dict[str, Dict[str, Any]] = {}
EMBEDDINGS: Optional[SentenceTransformerEmbeddings] = None
LLM: Optional[ChatOpenAI] = None
HYBRID_SEARCHER: Optional[HybridSearcher] = None
RERANKER: Optional[CrossEncoderReranker] = None


@app.on_event("startup")
def startup_event() -> None:
    global DB_MODEL_STORE, EMBEDDINGS, LLM, HYBRID_SEARCHER, RERANKER

    config_path = _resolve_server_config_path()
    cfg_store = _build_cfg_store(config_path)
    DB_MODEL_STORE = cfg_store.get("db_model_store", {})

    if not DB_MODEL_STORE:
        raise RuntimeError(
            "UMRS configuration loaded but db_model_store is empty. "
            "Ensure the server configuration lists at least one user/experience "
            "with store_embeddings = 'yes'."
        )

    model_name = os.getenv("UMRS_RAG_EMBEDDING_MODEL")
    if not model_name:
        # Auto-detect from the user config (matches the model used for ingestion)
        model_name = _detect_embedding_model_from_config(DB_MODEL_STORE)
    if not model_name:
        model_name = "sentence-transformers/all-MiniLM-L6-v2"
    EMBEDDINGS = PrefixedSentenceTransformerEmbeddings(model_name=model_name)

    # Configure LLM client against OpenAI-compatible vLLM endpoint
    vllm_base_url = os.getenv("VLLM_BASE_URL", "http://localhost:8000/v1")
    vllm_api_key = os.getenv("VLLM_API_KEY", "sk-umrs-demo")
    llm_model_name = os.getenv(
        "UMRS_RAG_LLM_MODEL",
        "microsoft/Phi-3-mini-4k-instruct",
    )

    LLM = ChatOpenAI(
        model=llm_model_name,
        base_url=vllm_base_url,
        api_key=vllm_api_key,
        temperature=0.1,
    )

    # Hybrid search and cross-encoder reranking (opt-in via request fields)
    HYBRID_SEARCHER = HybridSearcher()
    reranker_model = os.getenv(
        "UMRS_RAG_RERANKER_MODEL", "cross-encoder/ms-marco-MiniLM-L-6-v2"
    )
    reranker_device = os.getenv("UMRS_RAG_RERANKER_DEVICE", "cpu")
    RERANKER = CrossEncoderReranker(
        model_name=reranker_model, device=reranker_device
    )


@app.post("/rag/search", response_model=RAGSearchResponse)
def rag_search(payload: RAGSearchRequest) -> RAGSearchResponse:
    if EMBEDDINGS is None:
        raise HTTPException(status_code=500, detail="Embeddings backend not initialized")

    try:
        # Fetch more candidates when using hybrid or reranking so the
        # second-stage ranker has enough material to work with.
        fetch_k = payload.top_k
        if payload.search_method == "hybrid" or payload.enable_reranking:
            fetch_k = payload.top_k * 3

        retriever = UMRSPgVectorRetriever(
            db_model_store=DB_MODEL_STORE,
            embeddings=EMBEDDINGS,
            user=payload.user,
            xp_name=payload.xp_name,
            bucket_alias=payload.bucket_alias,
            modality=payload.modality,
            top_k=fetch_k,
        )
        docs = retriever.get_relevant_documents(payload.query)
    except ValueError as exc:
        raise HTTPException(status_code=400, detail=str(exc)) from exc
    except Exception as exc:  # pragma: no cover - defensive
        raise HTTPException(status_code=500, detail=str(exc)) from exc

    results: List[RAGSearchResultItem] = []

    if payload.search_method == "hybrid" and HYBRID_SEARCHER is not None and docs:
        # Build candidate tuples for hybrid search.
        # BM25 + RRF fusion on the retrieved candidate pool
        hybrid_results = HYBRID_SEARCHER.search(
            query=payload.query,
            documents=[
                (str(doc.metadata.get("id", i)), doc.page_content,
                 _cosine_score(doc.metadata.get("distance")))
                for i, doc in enumerate(docs)
            ],
            top_k=fetch_k,
        )

        # Optionally rerank
        if payload.enable_reranking and RERANKER is not None:
            hybrid_results = RERANKER.rerank(
                query=payload.query,
                results=hybrid_results,
                top_k=payload.top_k,
            )
        else:
            hybrid_results = hybrid_results[: payload.top_k]

        # Map back to response items; use the doc metadata from the original
        # retrieval for full context.
        doc_by_id = {str(doc.metadata.get("id", i)): doc for i, doc in enumerate(docs)}
        for sr in hybrid_results:
            orig_doc = doc_by_id.get(sr.document_id)
            meta = dict(orig_doc.metadata) if orig_doc else {}
            meta["hybrid_score"] = sr.score
            if sr.bm25_score is not None:
                meta["bm25_score"] = sr.bm25_score
            if sr.vector_score is not None:
                meta["vector_score"] = sr.vector_score
            if sr.rerank_score is not None:
                meta["rerank_score"] = sr.rerank_score
            results.append(
                RAGSearchResultItem(
                    id=int(meta.get("id", 0)),
                    score=sr.rerank_score if sr.rerank_score is not None else sr.score,
                    content=sr.content,
                    metadata=meta,
                )
            )
    else:
        # Pure vector search (default path)
        if payload.enable_reranking and RERANKER is not None and docs:
            search_results = [
                SearchResult(
                    document_id=str(doc.metadata.get("id", i)),
                    chunk_id=str(doc.metadata.get("id", i)),
                    content=doc.page_content,
                    score=_cosine_score(doc.metadata.get("distance")),
                    metadata=dict(doc.metadata),
                )
                for i, doc in enumerate(docs)
            ]
            reranked = RERANKER.rerank(
                query=payload.query,
                results=search_results,
                top_k=payload.top_k,
            )
            for sr in reranked:
                meta = sr.metadata
                meta["rerank_score"] = sr.rerank_score
                results.append(
                    RAGSearchResultItem(
                        id=int(meta.get("id", 0)),
                        score=sr.rerank_score if sr.rerank_score is not None else sr.score,
                        content=sr.content,
                        metadata=meta,
                    )
                )
        else:
            for doc in docs[: payload.top_k]:
                meta = dict(doc.metadata)
                row_id = int(meta.get("id", 0))
                score = _cosine_score(meta.get("distance"))
                results.append(
                    RAGSearchResultItem(
                        id=row_id,
                        score=score,
                        content=doc.page_content,
                        metadata=meta,
                    )
                )

    return RAGSearchResponse(results=results)


@app.post("/rag/qa", response_model=RAGQAResponse)
def rag_qa(payload: RAGQARequest) -> RAGQAResponse:
    """Agentic RAG endpoint backed by UMRS + vLLM.

    The pipeline is deliberately simple and stateless:

    1. (Optional) Ask the LLM to rewrite the user question into one or
       more search-oriented sub-queries.
    2. Run UMRS pgvector retrieval for each sub-query.
    3. Deduplicate and rank chunks.
    4. Ask the LLM to answer using only the retrieved context.
    """

    if EMBEDDINGS is None:
        raise HTTPException(status_code=500, detail="Embeddings backend not initialized")
    if LLM is None:
        raise HTTPException(status_code=500, detail="LLM backend not initialized")

    try:
        # Fetch more candidates when hybrid or reranking is requested
        fetch_k = payload.top_k
        if payload.search_method == "hybrid" or payload.enable_reranking:
            fetch_k = payload.top_k * 3

        retriever = UMRSPgVectorRetriever(
            db_model_store=DB_MODEL_STORE,
            embeddings=EMBEDDINGS,
            user=payload.user,
            xp_name=payload.xp_name,
            bucket_alias=payload.bucket_alias,
            modality=payload.modality,
            top_k=fetch_k,
        )
    except ValueError as exc:
        raise HTTPException(status_code=400, detail=str(exc)) from exc

    # Step 1: optional query rewrite into focused sub-queries
    rewritten_queries: List[str]
    if payload.enable_query_rewrite:
        system_prompt = (
            "You are a search assistant. Given a user's question, "
            "produce 1-3 short, concrete search queries that would "
            "retrieve the most relevant documents from a vector "
            "database. Return them as a numbered list, one per line."
        )
        msgs = [
            SystemMessage(content=system_prompt),
            HumanMessage(
                content=(
                    "User question: "
                    + payload.query
                    + "\nGenerate search queries:"
                )
            ),
        ]

        try:
            rewrite_resp = LLM.invoke(msgs)
            text = (
                rewrite_resp.content
                if hasattr(rewrite_resp, "content")
                else str(rewrite_resp)
            )
        except Exception:
            # Fail-soft if the LLM is temporarily unavailable; fall back to
            # using the original user query for retrieval.
            text = payload.query
        # Split on lines, strip numbering/bullets
        candidates: List[str] = []
        for line in str(text).splitlines():
            line = line.strip()
            if not line:
                continue
            # Remove common list prefixes like "1.", "-", "*"
            if line[0].isdigit() and "." in line:
                line = line.split(".", 1)[1].strip()
            if line.startswith(("- ", "* ")):
                line = line[2:].strip()
            if line:
                candidates.append(line)
        rewritten_queries = candidates or [payload.query]
    else:
        rewritten_queries = [payload.query]

    # Step 2: retrieve documents for each sub-query
    all_docs: List[Document] = []
    for q in rewritten_queries:
        try:
            all_docs.extend(retriever.get_relevant_documents(q))
        except Exception:
            # Fail-soft on individual sub-query errors
            continue

    if not all_docs:
        raise HTTPException(
            status_code=404,
            detail=(
                "No documents retrieved for the given query and filters. "
                "Check user/xp_name/bucket_alias/modality."
            ),
        )

    # Step 3: deduplicate + keep best by score
    by_key: Dict[str, Document] = {}
    for doc in all_docs:
        meta = doc.metadata or {}
        key_parts = [str(meta.get("id")), str(meta.get("chunk_md5"))]
        key = "::".join(key_parts)
        score = _cosine_score(meta.get("distance"))
        existing = by_key.get(key)
        if existing is None:
            by_key[key] = doc
        else:
            existing_score = _cosine_score((existing.metadata or {}).get("distance"))
            if score > existing_score:
                by_key[key] = doc

    unique_docs = list(by_key.values())

    # Sort by score descending and keep the top N
    def _score(doc: Document) -> float:
        return _cosine_score((doc.metadata or {}).get("distance"))

    unique_docs.sort(key=_score, reverse=True)

    # Optional: apply hybrid BM25+RRF fusion on the candidate pool
    if payload.search_method == "hybrid" and HYBRID_SEARCHER is not None and unique_docs:
        hybrid_results = HYBRID_SEARCHER.search(
            query=payload.query,
            documents=[
                (str(doc.metadata.get("id", i)), doc.page_content,
                 _cosine_score((doc.metadata or {}).get("distance")))
                for i, doc in enumerate(unique_docs)
            ],
            top_k=len(unique_docs),
        )
        # Re-order unique_docs by hybrid score
        doc_by_id = {str(doc.metadata.get("id", i)): doc for i, doc in enumerate(unique_docs)}
        unique_docs = [
            doc_by_id[sr.document_id]
            for sr in hybrid_results
            if sr.document_id in doc_by_id
        ]

    # Optional: cross-encoder reranking
    if payload.enable_reranking and RERANKER is not None and unique_docs:
        search_results = [
            SearchResult(
                document_id=str(doc.metadata.get("id", i)),
                chunk_id=str(doc.metadata.get("id", i)),
                content=doc.page_content,
                score=_cosine_score(doc.metadata.get("distance")),
                metadata=dict(doc.metadata),
            )
            for i, doc in enumerate(unique_docs)
        ]
        reranked = RERANKER.rerank(
            query=payload.query,
            results=search_results,
            top_k=payload.max_context_chunks,
        )
        # Rebuild unique_docs in reranked order
        doc_by_id = {str(doc.metadata.get("id", i)): doc for i, doc in enumerate(unique_docs)}
        unique_docs = [
            doc_by_id[sr.document_id]
            for sr in reranked
            if sr.document_id in doc_by_id
        ]

    top_docs = unique_docs[: payload.max_context_chunks]

    # Step 4: ask LLM to answer using only retrieved context
    default_system = (
        "You are a helpful assistant answering questions over a "
        "vector database. Use only the provided context snippets. "
        "If the answer is not contained in the context, say that "
        "you do not know instead of inventing information."
    )
    system_prompt = payload.system_prompt or default_system

    context_blocks: List[str] = []
    for i, doc in enumerate(top_docs, start=1):
        meta = doc.metadata or {}
        header = f"[Chunk {i}] user={meta.get('user')} xp={meta.get('xp_name')} " \
            f"bucket={meta.get('bucket_alias')} s3_object={meta.get('s3_object')}"
        body = doc.page_content or ""
        context_blocks.append(header + "\n" + body)

    context_text = "\n\n".join(context_blocks)
    answer_messages = [
        SystemMessage(content=system_prompt),
        HumanMessage(
            content=(
                "Question: "
                + payload.query
                + "\n\nContext:\n"
                + context_text
                + "\n\nAnswer based only on this context."
            )
        ),
    ]

    try:
        answer_resp = LLM.invoke(answer_messages)
        answer_text = (
            answer_resp.content
            if hasattr(answer_resp, "content")
            else str(answer_resp)
        )
    except Exception as exc:
        # Surface retrieval contexts even if the LLM is unavailable so that
        # downstream callers (including automated demos) can still validate
        # the data plane behaviour.
        answer_text = (
            "LLM backend error while generating answer: "
            + f"{type(exc).__name__}: {exc}"
        )

    # Build response contexts using the same schema as /rag/search
    results: List[RAGSearchResultItem] = []
    for doc in top_docs:
        meta = dict(doc.metadata or {})
        row_id = int(meta.get("id", 0))
        score = _cosine_score(meta.get("distance"))
        results.append(
            RAGSearchResultItem(
                id=row_id,
                score=score,
                content=doc.page_content or "",
                metadata=meta,
            )
        )

    return RAGQAResponse(
        answer=answer_text,
        contexts=results,
        rewritten_queries=rewritten_queries,
    )


