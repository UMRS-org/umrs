@app.post("/rag/query", response_model=GatewayQueryResponse)
def rag_query(payload: GatewayQueryRequest) -> GatewayQueryResponse:
    """Gateway-compatible RAG query endpoint.

    Wraps the internal /rag/qa endpoint with Gateway's expected format.
    """
    if EMBEDDINGS is None:
        raise HTTPException(status_code=500, detail="Embeddings backend not initialized")
    if LLM is None:
        raise HTTPException(status_code=500, detail="LLM backend not initialized")

    # Map Gateway request to internal format
    internal_request = RAGQARequest(
        query=payload.query,
        top_k=payload.top_k,
        user=None,  # Could extract from project_id mapping
        modality="text",
        bucket_alias=None,
        xp_name=payload.project_id,  # Use project_id as experience name
        max_context_chunks=payload.top_k,
        enable_query_rewrite=True,
    )

    # Call internal endpoint
    internal_response = rag_qa(internal_request)

    # Map internal response to Gateway format
    sources: List[GatewaySource] = []
    if payload.include_sources:
        for ctx in internal_response.contexts:
            if ctx.score >= payload.threshold:
                sources.append(
                    GatewaySource(
                        document_id=str(ctx.id),
                        content=ctx.content,
                        score=ctx.score,
                        metadata=ctx.metadata,
                    )
                )

    return GatewayQueryResponse(
        answer=internal_response.answer,
        sources=sources,
        usage=None,  # Token usage not tracked currently
    )


