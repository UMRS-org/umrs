class PrefixedSentenceTransformerEmbeddings(SentenceTransformerEmbeddings):
    """SentenceTransformerEmbeddings with automatic E5 query/document prefixes.

    E5 models require 'query: ' prefix for search queries and 'passage: '
    prefix for documents.  This wrapper applies the correct prefix
    transparently based on the model name.
    """

    def embed_query(self, text: str) -> list[float]:
        text = add_query_prefix(text, self.model_name)
        return super().embed_query(text)

    def embed_documents(self, texts: list[str]) -> list[list[float]]:
        texts = add_document_prefix(texts, self.model_name)
        return super().embed_documents(texts)


def _detect_embedding_model_from_config(
    db_model_store: dict[str, dict[str, Any]],
) -> str | None:
    """Extract the embedding model name from the first text-modality entry."""
    for entry in db_model_store.values():
        if entry.get("modality_name") == "text" and entry.get("store_embeddings_flag"):
            model_name = _model_name_from_entry(entry.get("model"))
            if model_name:
                return model_name
    return None


def _detect_ingestion_models_from_config(
    db_model_store: dict[str, dict[str, Any]],
) -> set[str]:
    """Return model names already used for ingestion/search backends."""
    models: set[str] = set()
    for entry in db_model_store.values():
        if not entry.get("store_embeddings_flag"):
            continue
        model_name = _model_name_from_entry(entry.get("model"))
        if model_name:
            models.add(model_name)
    return models


_THINK_BLOCK_RE = re.compile(r"<think>.*?</think>\s*", re.IGNORECASE | re.DOTALL)


def _strip_reasoning_blocks(text: str) -> str:
    """Remove model reasoning blocks such as <think>…</think>."""
    if not text:
        return ""

    cleaned = _THINK_BLOCK_RE.sub("", text).strip()
    if cleaned:
        return cleaned

    stripped = text.strip()
    if stripped.lower().startswith("<think>"):
        return ""
    return stripped


def _strip_numbering(line: str) -> str:
    if line and line[0].isdigit() and "." in line:
        return line.split(".", 1)[1].strip()
    return line


def _strip_outer_quotes(line: str) -> str:
    if line[0] == line[-1] and line[0] in {'"', "'"}:
        return line[1:-1].strip()
    return line


def _clean_rewrite_line(line: str) -> str:
    """Normalize one rewrite-output line ('' means skip it)."""
    line = line.strip()
    if not line:
        return ""
    line = _strip_numbering(line)
    if line.startswith(("- ", "* ")):
        line = line[2:].strip()
    return _strip_outer_quotes(line)


def _extract_rewritten_queries(raw_text: str, fallback_query: str) -> list[str]:
    """Turn LLM rewrite output into concrete search queries."""
    cleaned = _strip_reasoning_blocks(raw_text)
    candidates = [
        query for line in cleaned.splitlines() if (query := _clean_rewrite_line(line))
    ]
    return candidates or [fallback_query]


