def _resolve_llm_api_key() -> str:
    """Resolve the API key used for OpenAI-compatible QA requests.

    #211: an empty string means "no key configured" — callers already send
    no Authorization header for empty keys. A synthetic ``sk-umrs-demo``
    default previously made misconfigured deployments LOOK configured and
    buried the failure in a downstream 401 far from the cause.
    """
    _inject_site_env_defaults()

    for env_name in ("UMRS_RAG_LLM_API_KEY", "VLLM_API_KEY", "LITELLM_MASTER_KEY"):
        value = os.getenv(env_name)
        if value:
            return value

    try:
        site_cfg = get_site_config()
        if site_cfg.network.litellm_master_key:
            return site_cfg.network.litellm_master_key
    except Exception:
        pass

    logger.warning(
        "RAG LLM API key is not configured (checked UMRS_RAG_LLM_API_KEY, "
        "VLLM_API_KEY, LITELLM_MASTER_KEY, site network.litellm_master_key) — "
        "QA requests will be sent without an Authorization header. "
        "Set one of these if the upstream requires authentication."
    )
    return ""


def _endpoint_sort_key(endpoint: RegisteredEndpoint) -> tuple[int, Any]:
    """Sort usable endpoints ahead of stale transitional ones and prefer activity."""
    activity = endpoint.last_used_at or endpoint.ready_at or endpoint.created_at
    status_rank = {
        EndpointStatus.READY: 3,
        EndpointStatus.DEGRADED: 2,
        EndpointStatus.STARTING: 1,
        EndpointStatus.PROVISIONING: 0,
    }
    return (status_rank.get(endpoint.status, -1), activity)


def _endpoint_supports_openai(endpoint: RegisteredEndpoint) -> bool:
    metadata = endpoint.metadata or {}
    if "supports_openai" in metadata:
        return bool(metadata["supports_openai"])

    if endpoint.backend == "slurm-podman":
        return True

    model_name = str(endpoint.model)
    return model_name.startswith("openai://") or ":openai://" in model_name


def _resolve_registry_base_url(endpoint: RegisteredEndpoint) -> str:
    metadata = endpoint.metadata or {}
    port = metadata.get("litellm_port")

    if port is None and (
        endpoint.backend == "slurm-podman"
        or "rivault_profiles" in metadata
        or "supports_openai" in metadata
    ):
        try:
            port = get_site_config().network.litellm_port
        except Exception:
            port = os.getenv("NGINX_LITELLM_DOCKER_PORT") or os.getenv(
                "RIVAULT_REMOTE_PORT"
            )

    resolved_port = int(port or endpoint.port)
    return f"http://{endpoint.host}:{resolved_port}/v1"


def _list_remote_models(base_url: str, api_key: str) -> list[str]:
    headers = {"Authorization": f"Bearer {api_key}"} if api_key else None
    try:
        with httpx.Client(timeout=2.0, trust_env=False) as client:
            resp = client.get(base_url.rstrip("/") + "/models", headers=headers)
        if resp.status_code != 200:
            return []
        payload = resp.json()
    except Exception:
        return []

    models: list[str] = []
    for item in payload.get("data", []):
        model_id = str(item.get("id", "")).strip()
        if model_id:
            models.append(model_id)
    return models


def _build_registry_candidate_models(
    endpoint: RegisteredEndpoint,
    desired_model: str,
    known_ingestion_models: set[str],
    api_key: str,
) -> tuple[str, list[str]]:
    base_url = _resolve_registry_base_url(endpoint)
    available_models = _list_remote_models(base_url, api_key)

    if desired_model in available_models:
        return base_url, [desired_model]

    candidate_models = [
        model_name
        for model_name in available_models
        if model_name not in known_ingestion_models
    ]

    if candidate_models:
        return base_url, candidate_models

    model_name = str(endpoint.model)
    if model_name == desired_model or (
        model_name not in known_ingestion_models and "://" not in model_name
    ):
        return base_url, [model_name]

    return base_url, []


def _probeable_registry_endpoints(
    endpoints: list[RegisteredEndpoint],
) -> list[RegisteredEndpoint]:
    """Return non-terminal endpoints worth probing when readiness lags."""
    return [
        endpoint
        for endpoint in endpoints
        if endpoint.status in (EndpointStatus.STARTING, EndpointStatus.PROVISIONING)
    ]


def _collect_registry_candidates(
    endpoints: list[RegisteredEndpoint],
    *,
    matches_desired: bool,
    desired_model: str,
    known_ingestion_models: set[str],
    api_key: str,
    source: str,
    add_candidate: Callable[[ResolvedLLMEndpoint], None],
) -> None:
    """Add candidates from one registry slice (exact match or fallback)."""
    matched = sorted(
        [
            endpoint
            for endpoint in endpoints
            if (endpoint.model == desired_model) == matches_desired
        ],
        key=_endpoint_sort_key,
        reverse=True,
    )
    for endpoint in matched:
        if not _endpoint_supports_openai(endpoint):
            continue
        base_url, candidate_models = _build_registry_candidate_models(
            endpoint,
            desired_model,
            known_ingestion_models,
            api_key,
        )
        for model_name in candidate_models:
            add_candidate(
                ResolvedLLMEndpoint(
                    model_name=model_name,
                    base_url=base_url,
                    api_key=api_key,
                    source=source,
                    job_id=endpoint.job_id,
                )
            )


def _build_llm_candidates() -> list[ResolvedLLMEndpoint]:
    """Build an ordered list of QA LLM candidates.

    Precedence:
    1. Explicit `VLLM_BASE_URL` override when configured.
    2. Ready registry endpoints that exactly match `UMRS_RAG_LLM_MODEL`.
    3. Other ready registry endpoints that do not look like ingestion models.
    4. Stale transitional registry endpoints when readiness status lags.
    5. Default localhost fallback (`http://localhost:8000/v1`).
    """
    _inject_site_env_defaults()

    desired_model = os.getenv(
        "UMRS_RAG_LLM_MODEL",
        "microsoft/Phi-3-mini-4k-instruct",
    )
    desired_project = os.getenv("UMRS_RAG_LLM_PROJECT_ID") or None
    api_key = _resolve_llm_api_key()
    seen: set[tuple[str, str]] = set()
    candidates: list[ResolvedLLMEndpoint] = []

    def add_candidate(candidate: ResolvedLLMEndpoint) -> None:
        key = (candidate.model_name, candidate.base_url)
        if key in seen:
            return
        seen.add(key)
        candidates.append(candidate)

    explicit_base_url = os.getenv("VLLM_BASE_URL")
    if explicit_base_url:
        add_candidate(
            ResolvedLLMEndpoint(
                model_name=desired_model,
                base_url=explicit_base_url,
                api_key=api_key,
                source="env",
            )
        )

    try:
        registry = get_registry()
        registry_endpoints = registry.list_all(project_id=desired_project)
    except Exception:
        registry_endpoints = []

    usable_registry_endpoints = [
        endpoint
        for endpoint in registry_endpoints
        if endpoint.status in (EndpointStatus.READY, EndpointStatus.DEGRADED)
    ]
    transitional_registry_endpoints = _probeable_registry_endpoints(registry_endpoints)

    known_ingestion_models = set(_detect_ingestion_models_from_config(DB_MODEL_STORE))

    _collect_registry_candidates(
        usable_registry_endpoints,
        matches_desired=True,
        desired_model=desired_model,
        known_ingestion_models=set(),
        api_key=api_key,
        source="registry-exact",
        add_candidate=add_candidate,
    )

    _collect_registry_candidates(
        usable_registry_endpoints,
        matches_desired=False,
        desired_model=desired_model,
        known_ingestion_models=known_ingestion_models,
        api_key=api_key,
        source="registry-fallback",
        add_candidate=add_candidate,
    )

    _collect_registry_candidates(
        transitional_registry_endpoints,
        matches_desired=True,
        desired_model=desired_model,
        known_ingestion_models=set(),
        api_key=api_key,
        source="registry-stale-exact",
        add_candidate=add_candidate,
    )

    _collect_registry_candidates(
        transitional_registry_endpoints,
        matches_desired=False,
        desired_model=desired_model,
        known_ingestion_models=known_ingestion_models,
        api_key=api_key,
        source="registry-stale-fallback",
        add_candidate=add_candidate,
    )

    if not explicit_base_url:
        default_base_url = "http://localhost:8000/v1"
        default_models = _list_remote_models(default_base_url, api_key)
        if desired_model in default_models:
            add_candidate(
                ResolvedLLMEndpoint(
                    model_name=desired_model,
                    base_url=default_base_url,
                    api_key=api_key,
                    source="default",
                )
            )

    return candidates


def _mark_registry_endpoint_used(job_id: str | None) -> None:
    if not job_id:
        return
    with contextlib.suppress(Exception):
        get_registry().mark_used(job_id)


