def _resolve_server_config_path() -> str:
    """Resolve the UMRS server configuration file path.

    This mirrors the logic in server_umrs.main() but without depending on CLI.
    """

    config_path = get_resolved_json_server_path()
    if os.path.isfile(config_path):
        return config_path

    raise RuntimeError(f"No valid UMRS server config file found at {config_path}")


def _build_cfg_store(configure_file: str) -> dict[str, Any]:
    """Load UMRS configuration and build a minimal cfg_store.

    This mirrors the *data* part of ``perform_initial_config`` without
    starting message queues:

    - Load the server JSON configuration.
    - Create a fresh ``ServerCfg`` instance.
    - Call ``configure_user`` for each user to populate ``buckets_cfg``.
    - Derive a lightweight ``db_model_store`` mapping from ``buckets_cfg``
      that RAG retrieval can use.
    """

    if not os.path.exists(configure_file):
        raise RuntimeError(f"Configuration file '{configure_file}' not found.")

    _admin_s3_configuration_file, users, _server_cfg_json = load_server_cfg_file(
        configure_file
    )

    # Reuse the same configuration logic as the main UMRS server but avoid
    # spinning up ZeroMQ, workers, etc.
    #
    # A single user with stale/invalid S3 credentials must NOT prevent the
    # RAG service from starting for everyone else. ``connect_to_s3`` calls
    # ``sys.exit(-1)`` on auth failure, so catch SystemExit as well.
    server_cfg = ServerCfg()
    for user in users:
        try:
            configure_user(user, server_cfg)
        except (SystemExit, Exception) as exc:  # noqa: BLE001
            username = user.get("username", "<unknown>")
            print(f"WARNING: skipping user '{username}' during RAG startup: {exc!r}")

    db_model_store: dict[str, dict[str, Any]] = {}
    for path_to_bucket, entry in server_cfg.buckets_cfg.items():
        # Flatten the ServerBucketEntry dataclass into a simple dict that
        # contains exactly what the RAG retriever needs.
        db_model_store[path_to_bucket] = {
            "path_to_bucket": path_to_bucket,
            "bucket_alias": entry.bucket_alias,
            "s3_username": entry.s3_username,
            "sql_username": entry.sql_username,
            "data_base": entry.data_base,
            "db_name": entry.db_name,
            "table_name": entry.table_name,
            "model": entry.model,
            "store_embeddings_flag": entry.store_embeddings_flag,
            "modality_name": entry.modality_name,
            "s3_connection": entry.s3_connection,
            "metadata": entry.metadata,
            "xp_name": entry.xp_name,
        }

    return {"db_model_store": db_model_store}


def _model_name_from_entry(model: Any) -> str | None:
    """Extract a model name from runtime or config-backed model definitions."""
    if model is None:
        return None
    if hasattr(model, "model_name"):
        return getattr(model, "model_name") or None
    if isinstance(model, dict):
        return model.get("model_name") or None
    if isinstance(model, str):
        return model or None
    return None


def _entry_matches(
    entry: dict[str, Any],
    *,
    user: str | None,
    xp_name: str | None,
    bucket_alias: str | None,
    modality: str | None,
) -> bool:
    """Match one db_model_store entry against retriever filters."""
    if user and entry.get("s3_username") != user:
        return False
    if xp_name and entry.get("xp_name") != xp_name:
        return False
    if bucket_alias and entry.get("bucket_alias") != bucket_alias:
        return False
    if modality and entry.get("modality_name") != modality:
        return False
    return bool(entry.get("store_embeddings_flag", False))


class UMRSPgVectorRetriever(BaseRetriever):
    """LangChain-compatible retriever over UMRS pgvector tables.

    For now this retriever assumes a single matching table per query,
    identified by (user, xp_name, bucket_alias, modality).
    """

    # Pydantic fields so that BaseRetriever / BaseModel can manage
    # attribute validation correctly.
    db_model_store: dict[str, dict[str, Any]]
    embeddings: SentenceTransformerEmbeddings
    user: str | None = None
    xp_name: str | None = None
    bucket_alias: str | None = None
    modality: str | None = "text"
    top_k: int = 5

    model_config = ConfigDict(arbitrary_types_allowed=True)

    def _select_entry(self) -> dict[str, Any]:
        """Select a single matching entry from db_model_store.

        We currently require that filters resolve to exactly one entry to
        keep SQL simpler. This can be generalized later.
        """

        matches: list[dict[str, Any]] = [
            entry
            for _path, entry in self.db_model_store.items()
            if _entry_matches(
                entry,
                user=self.user,
                xp_name=self.xp_name,
                bucket_alias=self.bucket_alias,
                modality=self.modality,
            )
        ]

        if not matches:
            raise ValueError(
                "No matching embedding table found for the given filters. "
                "Please check user/xp_name/bucket_alias/modality."
            )
        if len(matches) > 1:
            raise ValueError(
                "Multiple embedding tables match the given filters; "
                "please narrow the query (e.g. by xp_name or bucket_alias)."
            )
        return matches[0]

    def _get_relevant_documents(
        self,
        query: str,
        *,
        run_manager: CallbackManagerForRetrieverRun | None = None,
    ) -> list[Document]:
        from psycopg2 import sql

        if not self.db_model_store:
            raise ValueError(
                "UMRS db_model_store is empty; server may not be configured."
            )

        entry = self._select_entry()
        data_base = entry["data_base"]
        table_name = entry["table_name"]
        xp_name = entry.get("xp_name")
        username = entry.get("s3_username")
        bucket_alias = entry.get("bucket_alias")

        # Compute query embedding using LangChain
        query_vec = self.embeddings.embed_query(query)

        db_pool = data_base.db_pool
        conn = db_pool.getconn()
        cur = conn.cursor()
        try:
            # For text modalities we expect _content and chunk_* columns.
            has_content = data_base.has_column(table_name, "_content")

            if has_content:
                query_sql = sql.SQL(
                    """
                    SELECT
                        id,
                        s3_object,
                        embedding <=> %s::vector AS distance,
                        _content,
                        chunk_start,
                        chunk_end,
                        chunk_md5,
                        checksum,
                        model
                    FROM {table}
                    WHERE embedding IS NOT NULL
                    ORDER BY embedding <=> %s::vector
                    LIMIT %s;
                    """
                ).format(table=sql.Identifier(table_name))
            else:
                query_sql = sql.SQL(
                    """
                    SELECT
                        id,
                        s3_object,
                        embedding <=> %s::vector AS distance,
                        NULL AS _content,
                        NULL AS chunk_start,
                        NULL AS chunk_end,
                        NULL AS chunk_md5,
                        checksum,
                        model
                    FROM {table}
                    WHERE embedding IS NOT NULL
                    ORDER BY embedding <=> %s::vector
                    LIMIT %s;
                    """
                ).format(table=sql.Identifier(table_name))

            cur.execute(query_sql, (query_vec, query_vec, self.top_k))
            rows = cur.fetchall()
        finally:
            cur.close()
            db_pool.putconn(conn)

        docs: list[Document] = []
        for row in rows:
            (
                row_id,
                s3_object,
                distance,
                content,
                chunk_start,
                chunk_end,
                chunk_md5,
                checksum,
                model_name,
            ) = row

            page_content = content or ""
            metadata: dict[str, Any] = {
                "id": row_id,
                "s3_object": s3_object,
                "distance": float(distance) if distance is not None else None,
                "checksum": checksum,
                "model": model_name,
                "chunk_start": chunk_start,
                "chunk_end": chunk_end,
                "chunk_md5": chunk_md5,
                "user": username,
                "bucket_alias": bucket_alias,
                "xp_name": xp_name,
            }

            docs.append(Document(page_content=page_content, metadata=metadata))

        return docs

    # Compatibility shim for LangChain retriever API.
    # Recent versions of langchain-core expose the retriever as a
    # Runnable (use ``invoke`` / ``ainvoke``) and no longer define
    # ``get_relevant_documents`` on BaseRetriever. Our service code
    # still calls ``get_relevant_documents``, so we provide a thin
    # wrapper that delegates to ``_get_relevant_documents``.

    def get_relevant_documents(
        self,
        query: str,
        *,
        run_manager: CallbackManagerForRetrieverRun | None = None,
    ) -> list[Document]:
        return self._get_relevant_documents(query, run_manager=run_manager)


