def _cosine_score(distance) -> float:
    """Convert pgvector cosine distance to a similarity score in [0, 1].

    pgvector's ``<=>`` operator returns ``1 - cosine_similarity``, so the
    range is [0, 2].  We convert back to similarity with a floor of 0.
    """
    if distance is None:
        return 0.0
    return max(0.0, 1.0 - float(distance))


class RAGSearchRequest(BaseModel):
    query: str = Field(..., description="Natural language query to search with")
    top_k: int = Field(5, ge=1, le=100, description="Number of results to return")
    user: Optional[str] = Field(None, description="Optional UMRS username filter")
    modality: Optional[str] = Field("text", description="Data modality (e.g., 'text')")
    bucket_alias: Optional[str] = Field(
        None, description="Optional bucket alias to scope the search"
    )
    xp_name: Optional[str] = Field(
        None, description="Optional experience name to scope the search"
    )
    search_method: Optional[str] = Field(
        "vector",
        description=(
            "Search method: 'vector' (default, pure pgvector cosine), "
            "or 'hybrid' (BM25 + vector with Reciprocal Rank Fusion)."
        ),
    )
    enable_reranking: bool = Field(
        False,
        description="If true, apply cross-encoder reranking to improve relevance.",
    )


class RAGSearchResultItem(BaseModel):
    id: int
    score: float
    content: str
    metadata: Dict[str, Any]


class RAGSearchResponse(BaseModel):
    results: List[RAGSearchResultItem]


class RAGQARequest(RAGSearchRequest):
    """RAG question-answering request.

    Extends the basic search request with optional system prompt and
    a small control on how much "agentic" behaviour to use.
    """

    system_prompt: Optional[str] = Field(
        None,
        description=(
            "Optional system prompt to steer the assistant. "
            "If omitted, a default UMRS RAG prompt is used."
        ),
    )
    max_context_chunks: int = Field(
        8,
        ge=1,
        le=50,
        description="Maximum number of retrieved chunks to feed to the LLM.",
    )
    enable_query_rewrite: bool = Field(
        True,
        description=(
            "If true, the LLM first rewrites the query into more search-"
            "friendly sub‑queries before retrieval."
        ),
    )


class RAGQAResponse(BaseModel):
    answer: str
    contexts: List[RAGSearchResultItem]
    rewritten_queries: List[str] = Field(
        default_factory=list,
        description="Sub‑queries generated by the agent for retrieval.",
    )


def _resolve_server_config_path() -> str:
    """Resolve the UMRS server configuration file path.

    This mirrors the logic in server_umrs.main() but without depending on CLI.
    """

    umrs_cfg_dir = os.getenv(get_umrs_cfg_env_var_name())
    if umrs_cfg_dir and os.path.isdir(umrs_cfg_dir):
        return os.path.join(umrs_cfg_dir, get_default_json_server_file())

    default_dir = get_default_umrs_cfg_dir()
    if os.path.isdir(default_dir):
        return os.path.join(default_dir, get_default_json_server_file())

    raise RuntimeError(
        f"No valid UMRS configuration directory. Expected either {default_dir} "
        f"or the directory pointed to by {get_umrs_cfg_env_var_name()}"
    )


def _build_cfg_store(configure_file: str) -> Dict[str, Any]:
    """Load UMRS configuration and build a minimal cfg_store.

    This mirrors the *data* part of ``perform_initial_config`` without
    starting message queues:

    - Load the server JSON configuration.
    - Create a fresh ``ServerCfg`` instance.
    - Call ``configure_user`` for each user to populate ``buckets_cfg``.
    - Derive a lightweight ``db_model_store`` mapping from ``buckets_cfg``
      that RAG retrieval can use.
    """

    if not os.path.exists(configure_file):
        raise RuntimeError(f"Configuration file '{configure_file}' not found.")

    _admin_s3_configuration_file, users, _server_cfg_json = load_server_cfg_file(
        configure_file
    )

    # Reuse the same configuration logic as the main UMRS server but avoid
    # spinning up ZeroMQ, workers, etc.
    server_cfg = ServerCfg()
    for user in users:
        configure_user(user, server_cfg)

    db_model_store: Dict[str, Dict[str, Any]] = {}
    for path_to_bucket, entry in server_cfg.buckets_cfg.items():
        # Flatten the ServerBucketEntry dataclass into a simple dict that
        # contains exactly what the RAG retriever needs.
        db_model_store[path_to_bucket] = {
            "path_to_bucket": path_to_bucket,
            "bucket_alias": entry.bucket_alias,
            "s3_username": entry.s3_username,
            "sql_username": entry.sql_username,
            "data_base": entry.data_base,
            "db_name": entry.db_name,
            "table_name": entry.table_name,
            "model": entry.model,
            "store_embeddings_flag": entry.store_embeddings_flag,
            "modality_name": entry.modality_name,
            "s3_connection": entry.s3_connection,
            "metadata": entry.metadata,
            "xp_name": entry.xp_name,
        }

    return {"db_model_store": db_model_store}


class UMRSPgVectorRetriever(BaseRetriever):
    """LangChain-compatible retriever over UMRS pgvector tables.

    For now this retriever assumes a single matching table per query,
    identified by (user, xp_name, bucket_alias, modality).
    """
    # Pydantic fields so that BaseRetriever / BaseModel can manage
    # attribute validation correctly.
    db_model_store: Dict[str, Dict[str, Any]]
    embeddings: SentenceTransformerEmbeddings
    user: Optional[str] = None
    xp_name: Optional[str] = None
    bucket_alias: Optional[str] = None
    modality: Optional[str] = "text"
    top_k: int = 5

    class Config:
        arbitrary_types_allowed = True

    def _select_entry(self) -> Dict[str, Any]:
        """Select a single matching entry from db_model_store.

        We currently require that filters resolve to exactly one entry to
        keep SQL simpler. This can be generalized later.
        """

        matches: List[Dict[str, Any]] = []
        for _path, entry in self.db_model_store.items():
            if self.user and entry.get("s3_username") != self.user:
                continue
            if self.xp_name and entry.get("xp_name") != self.xp_name:
                continue
            if self.bucket_alias and entry.get("bucket_alias") != self.bucket_alias:
                continue
            if self.modality and entry.get("modality_name") != self.modality:
                continue
            if not entry.get("store_embeddings_flag", False):
                continue
            matches.append(entry)

        if not matches:
            raise ValueError(
                "No matching embedding table found for the given filters. "
                "Please check user/xp_name/bucket_alias/modality."
            )
        if len(matches) > 1:
            raise ValueError(
                "Multiple embedding tables match the given filters; "
                "please narrow the query (e.g. by xp_name or bucket_alias)."
            )
        return matches[0]

    def _get_relevant_documents(
        self,
        query: str,
        *,
        run_manager: Optional[CallbackManagerForRetrieverRun] = None,
    ) -> List[Document]:
        from psycopg2 import sql

        if not self.db_model_store:
            raise ValueError("UMRS db_model_store is empty; server may not be configured.")

        entry = self._select_entry()
        data_base = entry["data_base"]
        table_name = entry["table_name"]
        xp_name = entry.get("xp_name")
        username = entry.get("s3_username")
        bucket_alias = entry.get("bucket_alias")

        # Compute query embedding using LangChain
        query_vec = self.embeddings.embed_query(query)

        db_pool = data_base.db_pool
        conn = db_pool.getconn()
        cur = conn.cursor()
        try:
            # For text modalities we expect _content and chunk_* columns.
            has_content = data_base.has_column(table_name, "_content")

            if has_content:
                query_sql = sql.SQL(
                    """
                    SELECT
                        id,
                        s3_object,
                        embedding <=> %s::vector AS distance,
                        _content,
                        chunk_start,
                        chunk_end,
                        chunk_md5,
                        checksum,
                        model
                    FROM {table}
                    WHERE embedding IS NOT NULL
                    ORDER BY embedding <=> %s::vector
                    LIMIT %s;
                    """
                ).format(table=sql.Identifier(table_name))
            else:
                query_sql = sql.SQL(
                    """
                    SELECT
                        id,
                        s3_object,
                        embedding <=> %s::vector AS distance,
                        NULL AS _content,
                        NULL AS chunk_start,
                        NULL AS chunk_end,
                        NULL AS chunk_md5,
                        checksum,
                        model
                    FROM {table}
                    WHERE embedding IS NOT NULL
                    ORDER BY embedding <=> %s::vector
                    LIMIT %s;
                    """
                ).format(table=sql.Identifier(table_name))

            cur.execute(query_sql, (query_vec, query_vec, self.top_k))
            rows = cur.fetchall()
        finally:
            cur.close()
            db_pool.putconn(conn)

        docs: List[Document] = []
        for row in rows:
            (
                row_id,
                s3_object,
                distance,
                content,
                chunk_start,
                chunk_end,
                chunk_md5,
                checksum,
                model_name,
            ) = row

            page_content = content or ""
            metadata: Dict[str, Any] = {
                "id": row_id,
                "s3_object": s3_object,
                "distance": float(distance) if distance is not None else None,
                "checksum": checksum,
                "model": model_name,
                "chunk_start": chunk_start,
                "chunk_end": chunk_end,
                "chunk_md5": chunk_md5,
                "user": username,
                "bucket_alias": bucket_alias,
                "xp_name": xp_name,
            }

            docs.append(Document(page_content=page_content, metadata=metadata))

        return docs

    # Compatibility shim for LangChain retriever API.
    # Recent versions of langchain-core expose the retriever as a
    # Runnable (use ``invoke`` / ``ainvoke``) and no longer define
    # ``get_relevant_documents`` on BaseRetriever. Our service code
    # still calls ``get_relevant_documents``, so we provide a thin
    # wrapper that delegates to ``_get_relevant_documents``.

    def get_relevant_documents(
        self,
        query: str,
        *,
        run_manager: Optional[CallbackManagerForRetrieverRun] = None,
    ) -> List[Document]:
        return self._get_relevant_documents(query, run_manager=run_manager)


