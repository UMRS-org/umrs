"""
Slurm orchestrator backend for Mini-RiVault.

Manages LLM inference endpoints via Slurm job scheduling and Singularity containers.
"""

from __future__ import annotations

import asyncio
import os
import re
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional

from .base import (
    EndpointInfo,
    JobInfo,
    JobStatus,
    OrchestratorBackend,
)


class SlurmBackend(OrchestratorBackend):
    """
    Slurm-based orchestrator for HPC environments.

    Uses sbatch for job submission and Singularity for containerization.
    Job info files are written to a shared directory for endpoint discovery.
    """

    @property
    def backend_name(self) -> str:
        return "slurm"

    def _job_info_path(self, job_id: str) -> Path:
        """Get path to job info file."""
        return Path(self.config.slurm_job_info_dir) / f"rivault-job-{job_id}.info"

    def _parse_job_info_file(self, path: Path) -> Dict[str, str]:
        """Parse a job info file into a dict."""
        info = {}
        if path.exists():
            with open(path, "r") as f:
                for line in f:
                    line = line.strip()
                    if "=" in line:
                        key, value = line.split("=", 1)
                        info[key] = value
        return info

    def _status_from_info(self, info: Dict[str, str]) -> JobStatus:
        """Convert job info status string to JobStatus enum."""
        status_map = {
            "pending": JobStatus.PENDING,
            "starting": JobStatus.STARTING,
            "ready": JobStatus.READY,
            "running": JobStatus.RUNNING,
            "failed": JobStatus.FAILED,
            "stopped": JobStatus.STOPPED,
        }
        return status_map.get(info.get("RIVAULT_STATUS", "").lower(), JobStatus.UNKNOWN)

    def _build_sbatch_script(self, model_path: str, **kwargs: Any) -> str:
        """Generate sbatch script content."""
        cfg = self.config

        # Allow kwargs to override config
        partition = kwargs.get("partition", cfg.slurm_partition)
        time_limit = kwargs.get("time", cfg.slurm_time)
        gpus = kwargs.get("gpus", cfg.slurm_gpus)
        cpus = kwargs.get("cpus", cfg.slurm_cpus)
        mem = kwargs.get("mem", cfg.slurm_mem)

        script = f"""#!/bin/bash
#SBATCH --job-name=mini-rivault
#SBATCH --partition={partition}
#SBATCH --time={time_limit}
#SBATCH --gres=gpu:{gpus}
#SBATCH --cpus-per-task={cpus}
#SBATCH --mem={mem}
#SBATCH --output=/var/log/rivault/job-%j.out
#SBATCH --error=/var/log/rivault/job-%j.err

# =============================================================================
# Mini-RiVault Slurm Job (Generated by UMRS Orchestrator)
# =============================================================================

set -e

# Configuration
VLLM_MODEL_PATH="{model_path}"
VLLM_PORT={cfg.vllm_port}
LITELLM_PORT={cfg.litellm_port}
LITELLM_MASTER_KEY="{cfg.litellm_master_key}"
VLLM_MAX_MODEL_LEN={cfg.vllm_max_model_len}
VLLM_MAX_NUM_SEQS={cfg.vllm_max_num_seqs}
VLLM_TENSOR_PARALLEL_SIZE={cfg.vllm_tensor_parallel_size}
VLLM_GPU_MEMORY_UTILIZATION={cfg.vllm_gpu_memory_utilization}
SINGULARITY_IMAGE="{cfg.singularity_image}"
JOB_INFO_DIR="{cfg.slurm_job_info_dir}"

echo "============================================="
echo "Mini-RiVault Slurm Job"
echo "============================================="
echo "Job ID:      $SLURM_JOB_ID"
echo "Node:        $(hostname)"
echo "Model:       $VLLM_MODEL_PATH"
echo "============================================="

# Create job info directory
mkdir -p "$JOB_INFO_DIR"

# Write initial job info for UMRS discovery
JOB_INFO_FILE="$JOB_INFO_DIR/rivault-job-${{SLURM_JOB_ID}}.info"
cat > "$JOB_INFO_FILE" << EOF
RIVAULT_JOB_ID=${{SLURM_JOB_ID}}
RIVAULT_NODE=$(hostname)
RIVAULT_LITELLM_PORT=${{LITELLM_PORT}}
RIVAULT_VLLM_PORT=${{VLLM_PORT}}
RIVAULT_MODEL_PATH=${{VLLM_MODEL_PATH}}
RIVAULT_START_TIME=$(date -Iseconds)
RIVAULT_STATUS=starting
EOF

# Cleanup function
cleanup() {{
    echo "Cleaning up..."
    if [[ -f "$JOB_INFO_FILE" ]]; then
        sed -i 's/RIVAULT_STATUS=.*/RIVAULT_STATUS=stopped/' "$JOB_INFO_FILE"
        echo "RIVAULT_STOP_TIME=$(date -Iseconds)" >> "$JOB_INFO_FILE"
    fi
    singularity instance stop rivault-${{SLURM_JOB_ID}} 2>/dev/null || true
    sleep 5
    rm -f "$JOB_INFO_FILE"
    echo "Cleanup complete."
}}
trap cleanup EXIT INT TERM

# Validate prerequisites
if [[ ! -f "$SINGULARITY_IMAGE" ]]; then
    echo "Error: Singularity image not found: $SINGULARITY_IMAGE"
    sed -i 's/RIVAULT_STATUS=.*/RIVAULT_STATUS=failed/' "$JOB_INFO_FILE"
    exit 1
fi

if [[ ! -d "$VLLM_MODEL_PATH" ]]; then
    echo "Error: Model path not found: $VLLM_MODEL_PATH"
    sed -i 's/RIVAULT_STATUS=.*/RIVAULT_STATUS=failed/' "$JOB_INFO_FILE"
    exit 1
fi

# Load modules
module load cuda/12.1 2>/dev/null || true
module load singularity 2>/dev/null || true

# Start Singularity container
echo "Starting Mini-RiVault..."
singularity run \\
    --nv \\
    --bind "${{VLLM_MODEL_PATH}}:/models:ro" \\
    --env VLLM_MODEL_PATH=/models \\
    --env VLLM_PORT=${{VLLM_PORT}} \\
    --env LITELLM_PORT=${{LITELLM_PORT}} \\
    --env LITELLM_MASTER_KEY=${{LITELLM_MASTER_KEY}} \\
    --env VLLM_MAX_MODEL_LEN=${{VLLM_MAX_MODEL_LEN}} \\
    --env VLLM_MAX_NUM_SEQS=${{VLLM_MAX_NUM_SEQS}} \\
    --env VLLM_TENSOR_PARALLEL_SIZE=${{VLLM_TENSOR_PARALLEL_SIZE}} \\
    --env VLLM_GPU_MEMORY_UTILIZATION=${{VLLM_GPU_MEMORY_UTILIZATION}} \\
    "$SINGULARITY_IMAGE" &

SINGULARITY_PID=$!

# Wait for readiness (check /v1/models with auth)
echo "Waiting for Mini-RiVault to be ready..."
READY=false
for i in $(seq 1 {cfg.startup_timeout_sec // 5}); do
    # Use /v1/models endpoint with auth as per README contract
    if curl -sf -H "Authorization: Bearer ${{LITELLM_MASTER_KEY}}" \\
       "http://localhost:${{LITELLM_PORT}}/v1/models" > /dev/null 2>&1; then
        READY=true
        break
    fi
    sleep 5
done

if $READY; then
    echo "Mini-RiVault is ready!"
    sed -i 's/RIVAULT_STATUS=.*/RIVAULT_STATUS=ready/' "$JOB_INFO_FILE"
    echo "RIVAULT_READY_TIME=$(date -Iseconds)" >> "$JOB_INFO_FILE"

    echo ""
    echo "============================================="
    echo "Mini-RiVault Ready"
    echo "============================================="
    echo "Node:     $(hostname)"
    echo "API:      http://$(hostname):${{LITELLM_PORT}}/v1/"
    echo "Job ID:   $SLURM_JOB_ID"
    echo "============================================="

    # Wait for container to exit or job timeout
    wait $SINGULARITY_PID
else
    echo "Error: Mini-RiVault failed to start within timeout"
    sed -i 's/RIVAULT_STATUS=.*/RIVAULT_STATUS=failed/' "$JOB_INFO_FILE"
    exit 1
fi
"""
        return script

    async def submit_job(
        self,
        model_path: Optional[str] = None,
        **kwargs: Any,
    ) -> JobInfo:
        """Submit a Slurm job for Mini-RiVault."""
        model = model_path or self.config.model_path
        if not model:
            raise ValueError("model_path is required (set VLLM_MODEL_PATH or pass explicitly)")

        # Generate sbatch script
        script_content = self._build_sbatch_script(model, **kwargs)

        # Submit via sbatch
        proc = await asyncio.create_subprocess_exec(
            "sbatch",
            "--parsable",
            stdin=asyncio.subprocess.PIPE,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
        )
        stdout, stderr = await proc.communicate(script_content.encode())

        if proc.returncode != 0:
            raise RuntimeError(f"sbatch failed: {stderr.decode()}")

        job_id = stdout.decode().strip().split(";")[0]  # Handle "JOBID;CLUSTER" format

        return JobInfo(
            job_id=job_id,
            status=JobStatus.PENDING,
            model_path=model,
            created_at=datetime.now(),
            backend=self.backend_name,
        )

    async def get_job_status(self, job_id: str) -> JobInfo:
        """Get status of a Slurm job."""
        info_path = self._job_info_path(job_id)

        # First check job info file (more detailed status)
        if info_path.exists():
            info = self._parse_job_info_file(info_path)
            status = self._status_from_info(info)

            endpoint = None
            if status in (JobStatus.READY, JobStatus.RUNNING):
                endpoint = EndpointInfo(
                    node=info.get("RIVAULT_NODE", "unknown"),
                    litellm_port=int(info.get("RIVAULT_LITELLM_PORT", "11434")),
                    vllm_port=int(info.get("RIVAULT_VLLM_PORT", "8000")),
                )

            return JobInfo(
                job_id=job_id,
                status=status,
                endpoint=endpoint,
                model_path=info.get("RIVAULT_MODEL_PATH", ""),
                backend=self.backend_name,
                metadata=info,
            )

        # Fall back to squeue
        proc = await asyncio.create_subprocess_exec(
            "squeue",
            "-j", job_id,
            "-h",
            "-o", "%T",  # State
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
        )
        stdout, _ = await proc.communicate()

        if proc.returncode != 0 or not stdout.strip():
            # Job not in queue - check sacct for completed/failed
            proc = await asyncio.create_subprocess_exec(
                "sacct",
                "-j", job_id,
                "-n",
                "-o", "State",
                stdout=asyncio.subprocess.PIPE,
                stderr=asyncio.subprocess.PIPE,
            )
            stdout, _ = await proc.communicate()
            state = stdout.decode().strip().split("\n")[0].strip() if stdout else ""

            if "COMPLETED" in state:
                status = JobStatus.STOPPED
            elif "FAILED" in state or "CANCELLED" in state:
                status = JobStatus.FAILED
            else:
                status = JobStatus.UNKNOWN
        else:
            slurm_state = stdout.decode().strip()
            state_map = {
                "PENDING": JobStatus.PENDING,
                "RUNNING": JobStatus.STARTING,  # May not be ready yet
                "COMPLETING": JobStatus.RUNNING,
                "COMPLETED": JobStatus.STOPPED,
                "FAILED": JobStatus.FAILED,
                "CANCELLED": JobStatus.STOPPED,
            }
            status = state_map.get(slurm_state, JobStatus.UNKNOWN)

        return JobInfo(
            job_id=job_id,
            status=status,
            backend=self.backend_name,
        )

    async def wait_for_ready(
        self,
        job_id: str,
        timeout_sec: Optional[int] = None,
    ) -> EndpointInfo:
        """Wait for job to be ready."""
        timeout = timeout_sec or self.config.startup_timeout_sec
        poll_interval = self.config.readiness_poll_interval_sec
        elapsed = 0

        while elapsed < timeout:
            job = await self.get_job_status(job_id)

            if job.status == JobStatus.FAILED:
                raise RuntimeError(f"Job {job_id} failed: {job.error_message}")

            if job.is_ready() and job.endpoint:
                # Double-check with actual HTTP call
                if await self.check_readiness(job.endpoint):
                    return job.endpoint

            await asyncio.sleep(poll_interval)
            elapsed += poll_interval

        raise TimeoutError(f"Job {job_id} did not become ready within {timeout}s")

    async def cleanup(self, job_id: str, force: bool = False) -> None:
        """Cancel a Slurm job."""
        signal = "KILL" if force else "TERM"
        proc = await asyncio.create_subprocess_exec(
            "scancel",
            f"--signal={signal}",
            job_id,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
        )
        await proc.communicate()

        # Clean up info file
        info_path = self._job_info_path(job_id)
        if info_path.exists():
            info_path.unlink()

    async def list_jobs(
        self,
        status_filter: Optional[List[JobStatus]] = None,
    ) -> List[JobInfo]:
        """List all Mini-RiVault jobs."""
        jobs = []

        # List from job info files
        info_dir = Path(self.config.slurm_job_info_dir)
        if info_dir.exists():
            for info_file in info_dir.glob("rivault-job-*.info"):
                match = re.search(r"rivault-job-(\d+)\.info", info_file.name)
                if match:
                    job_id = match.group(1)
                    job = await self.get_job_status(job_id)
                    if status_filter is None or job.status in status_filter:
                        jobs.append(job)

        # Also check squeue for pending jobs not yet in info files
        proc = await asyncio.create_subprocess_exec(
            "squeue",
            "-u", os.environ.get("USER", ""),
            "-n", "mini-rivault",
            "-h",
            "-o", "%i",
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
        )
        stdout, _ = await proc.communicate()

        if stdout:
            for job_id in stdout.decode().strip().split("\n"):
                job_id = job_id.strip()
                if job_id and not any(j.job_id == job_id for j in jobs):
                    job = await self.get_job_status(job_id)
                    if status_filter is None or job.status in status_filter:
                        jobs.append(job)

        return jobs

    async def cleanup_orphans(self) -> int:
        """Clean up orphaned job info files."""
        cleaned = 0
        info_dir = Path(self.config.slurm_job_info_dir)

        if not info_dir.exists():
            return 0

        for info_file in info_dir.glob("rivault-job-*.info"):
            match = re.search(r"rivault-job-(\d+)\.info", info_file.name)
            if not match:
                continue

            job_id = match.group(1)

            # Check if job still exists in Slurm
            proc = await asyncio.create_subprocess_exec(
                "squeue",
                "-j", job_id,
                "-h",
                stdout=asyncio.subprocess.PIPE,
                stderr=asyncio.subprocess.PIPE,
            )
            stdout, _ = await proc.communicate()

            if not stdout.strip():
                # Job no longer in queue, remove info file
                info_file.unlink()
                cleaned += 1

        return cleaned

    async def health_check(self) -> Dict[str, Any]:
        """Check if Slurm is accessible."""
        try:
            proc = await asyncio.create_subprocess_exec(
                "sinfo",
                "-h",
                "-p", self.config.slurm_partition,
                "-o", "%P %a %D",
                stdout=asyncio.subprocess.PIPE,
                stderr=asyncio.subprocess.PIPE,
            )
            stdout, stderr = await proc.communicate()

            if proc.returncode != 0:
                return {
                    "backend": self.backend_name,
                    "healthy": False,
                    "message": f"sinfo failed: {stderr.decode()}",
                }

            return {
                "backend": self.backend_name,
                "healthy": True,
                "message": "Slurm cluster accessible",
                "partition_info": stdout.decode().strip(),
            }
        except FileNotFoundError:
            return {
                "backend": self.backend_name,
                "healthy": False,
                "message": "Slurm commands not found (sinfo)",
            }
