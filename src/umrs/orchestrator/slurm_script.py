"""Rendering helpers for legacy Slurm/Singularity Mini-RiVault jobs."""

from __future__ import annotations

from typing import Any

from .base import OrchestratorConfig


def render_sbatch_script(
    cfg: OrchestratorConfig,
    model_path: str,
    **kwargs: Any,
) -> str:
    """Generate sbatch script content for a Singularity Mini-RiVault job."""
    partition = kwargs.get("partition_override") or kwargs.get("partition", cfg.slurm_partition)
    nodelist_hint = kwargs.get("nodelist_hint")
    time_limit = kwargs.get("time", cfg.slurm_time)
    gpus = kwargs.get("gpus", cfg.slurm_gpus)
    cpus = kwargs.get("cpus", cfg.slurm_cpus)
    mem = kwargs.get("mem", cfg.slurm_mem)
    return "\n".join(
        part.rstrip()
        for part in (
            _script_header(cfg, partition, nodelist_hint, time_limit, gpus, cpus, mem),
            _script_config(cfg, model_path),
            _script_job_info(),
            _script_cleanup(),
            _script_validation(),
            _script_launch(cfg),
            _script_readiness(cfg),
        )
    )


def module_load_lines(modules: list[str]) -> str:
    """Render configured module loads for the Slurm script."""
    if not modules:
        return "# No site modules configured"
    return "\n".join(f"module load {module} 2>/dev/null || true" for module in modules)


def _script_header(
    cfg: OrchestratorConfig,
    partition: str,
    nodelist_hint: str | None,
    time_limit: str,
    gpus: int,
    cpus: int,
    mem: str,
) -> str:
    nodelist = f"\n#SBATCH --nodelist={nodelist_hint}" if nodelist_hint else ""
    return f"""#!/bin/bash
#SBATCH --job-name=mini-rivault
#SBATCH --partition={partition}{nodelist}
#SBATCH --time={time_limit}
#SBATCH --gres=gpu:{gpus}
#SBATCH --cpus-per-task={cpus}
#SBATCH --mem={mem}
#SBATCH --output={cfg.slurm_log_dir}/job-%j.out
#SBATCH --error={cfg.slurm_log_dir}/job-%j.err

# =============================================================================
# Mini-RiVault Slurm Job (Generated by UMRS Orchestrator)
# =============================================================================

set -e"""


def _script_config(cfg: OrchestratorConfig, model_path: str) -> str:
    return f"""# Configuration
VLLM_MODEL_PATH=\"{model_path}\"
VLLM_PORT={cfg.vllm_port}
LITELLM_PORT={cfg.litellm_port}
LITELLM_MASTER_KEY=\"{cfg.litellm_master_key}\"
VLLM_MAX_MODEL_LEN={cfg.vllm_max_model_len}
VLLM_MAX_NUM_SEQS={cfg.vllm_max_num_seqs}
VLLM_TENSOR_PARALLEL_SIZE={cfg.vllm_tensor_parallel_size}
VLLM_GPU_MEMORY_UTILIZATION={cfg.vllm_gpu_memory_utilization}
SINGULARITY_IMAGE=\"{cfg.singularity_image}\"
JOB_INFO_DIR=\"{cfg.slurm_job_info_dir}\"

echo \"=============================================\"
echo \"Mini-RiVault Slurm Job\"
echo \"=============================================\"
echo \"Job ID:      $SLURM_JOB_ID\"
echo \"Node:        $(hostname)\"
echo \"Model:       $VLLM_MODEL_PATH\"
echo \"=============================================\""""


def _script_job_info() -> str:
    return """# Create job info directory
mkdir -p "$JOB_INFO_DIR"

# Write initial job info for UMRS discovery
JOB_INFO_FILE="$JOB_INFO_DIR/rivault-job-${SLURM_JOB_ID}.info"
cat > "$JOB_INFO_FILE" << EOF
RIVAULT_JOB_ID=${SLURM_JOB_ID}
RIVAULT_NODE=$(hostname)
RIVAULT_LITELLM_PORT=${LITELLM_PORT}
RIVAULT_VLLM_PORT=${VLLM_PORT}
RIVAULT_MODEL_PATH=${VLLM_MODEL_PATH}
RIVAULT_START_TIME=$(date -Iseconds)
RIVAULT_STATUS=starting
EOF"""


def _script_cleanup() -> str:
    return """# Cleanup function
cleanup() {
    echo "Cleaning up..."
    if [[ -f "$JOB_INFO_FILE" ]]; then
        sed -i 's/RIVAULT_STATUS=.*/RIVAULT_STATUS=stopped/' "$JOB_INFO_FILE"
        echo "RIVAULT_STOP_TIME=$(date -Iseconds)" >> "$JOB_INFO_FILE"
    fi
    singularity instance stop rivault-${SLURM_JOB_ID} 2>/dev/null || true
    sleep 5
    rm -f "$JOB_INFO_FILE"
    echo "Cleanup complete."
}
trap cleanup EXIT INT TERM"""


def _script_validation() -> str:
    return """# Validate prerequisites
if [[ ! -f "$SINGULARITY_IMAGE" ]]; then
    echo "Error: Singularity image not found: $SINGULARITY_IMAGE"
    sed -i 's/RIVAULT_STATUS=.*/RIVAULT_STATUS=failed/' "$JOB_INFO_FILE"
    exit 1
fi

if [[ ! -d "$VLLM_MODEL_PATH" ]]; then
    echo "Error: Model path not found: $VLLM_MODEL_PATH"
    sed -i 's/RIVAULT_STATUS=.*/RIVAULT_STATUS=failed/' "$JOB_INFO_FILE"
    exit 1
fi"""


def _script_launch(cfg: OrchestratorConfig) -> str:
    return f"""# Load modules
{module_load_lines(cfg.slurm_modules)}

# Start Singularity container
echo \"Starting Mini-RiVault...\"
singularity run \\
    --nv \\
    --bind \"${{VLLM_MODEL_PATH}}:/models:ro\" \\
    --env VLLM_MODEL_PATH=/models \\
    --env VLLM_PORT=${{VLLM_PORT}} \\
    --env LITELLM_PORT=${{LITELLM_PORT}} \\
    --env LITELLM_MASTER_KEY=${{LITELLM_MASTER_KEY}} \\
    --env VLLM_MAX_MODEL_LEN=${{VLLM_MAX_MODEL_LEN}} \\
    --env VLLM_MAX_NUM_SEQS=${{VLLM_MAX_NUM_SEQS}} \\
    --env VLLM_TENSOR_PARALLEL_SIZE=${{VLLM_TENSOR_PARALLEL_SIZE}} \\
    --env VLLM_GPU_MEMORY_UTILIZATION=${{VLLM_GPU_MEMORY_UTILIZATION}} \\
    \"$SINGULARITY_IMAGE\" &

SINGULARITY_PID=$!"""


def _script_readiness(cfg: OrchestratorConfig) -> str:
    return f"""# Wait for readiness (check /v1/models with auth)
echo \"Waiting for Mini-RiVault to be ready...\"
READY=false
for i in $(seq 1 {cfg.startup_timeout_sec // 5}); do
    if curl -sf -H \"Authorization: Bearer ${{LITELLM_MASTER_KEY}}\" \\
       \"http://localhost:${{LITELLM_PORT}}/v1/models\" > /dev/null 2>&1; then
        READY=true
        break
    fi
    sleep 5
done

if $READY; then
    echo \"Mini-RiVault is ready!\"
    sed -i 's/RIVAULT_STATUS=.*/RIVAULT_STATUS=ready/' \"$JOB_INFO_FILE\"
    echo \"RIVAULT_READY_TIME=$(date -Iseconds)\" >> \"$JOB_INFO_FILE\"

    echo \"\"
    echo \"=============================================\"
    echo \"Mini-RiVault Ready\"
    echo \"=============================================\"
    echo \"Node:     $(hostname)\"
    echo \"API:      http://$(hostname):${{LITELLM_PORT}}/v1/\"
    echo \"Job ID:   $SLURM_JOB_ID\"
    echo \"=============================================\"

    wait $SINGULARITY_PID
else
    echo \"Error: Mini-RiVault failed to start within timeout\"
    sed -i 's/RIVAULT_STATUS=.*/RIVAULT_STATUS=failed/' \"$JOB_INFO_FILE\"
    exit 1
fi
"""
