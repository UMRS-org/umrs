#!/usr/bin/env bash
# =============================================================================
# start.sh — Launch dual-cluster UMRS on umrs-front
# =============================================================================
# Starts:
#   - Postgres (podman container, port 5432)
#   - SeaweedFS S3 object store (podman container, port 9000; ADR-055)
#   - UMRS server for RCCS Cloud (ZMQ:50090, HTTP:8000)
#   - UMRS server for AI4S (ZMQ:50100, HTTP:8002)
#   - UMRS server for bdrt (ZMQ:50110, HTTP:8004)
#   - UMRS server for octopus (ZMQ:50120, HTTP:8006)
#
# Prerequisites:
#   - Podman (rootless) with compose support
#   - Edit .env
#
# Usage:
#   ./start.sh              # Start everything
#   ./start.sh --server     # Restart UMRS servers only (keep containers)
# =============================================================================
set -euo pipefail
cd "$(dirname "$0")"

export PATH="$HOME/.local/bin:$PATH"
export GOMAXPROCS="${GOMAXPROCS:-4}"

SCRIPT_DIR="$(pwd)"
REPO_ROOT="$(cd ../.. && pwd)"
LOG_DIR="${SCRIPT_DIR}/logs"

# Container image used for both UMRS servers and utility tasks (key gen, S3 bootstrap, etc.)
UMRS_IMAGE="localhost/umrs-server:latest"

START_MODE="${1:-}"

# ─── Prerequisites ───────────────────────────────────────────────────────────
[[ "$(uname -s)" == "Linux" ]] || { echo "ERROR: Must run on umrs-front (Linux)"; exit 1; }

# ─── SeaweedFS IAM/STS config renderer (ADR-055) ─────────────────────────────
# Writes seaweedfs/iam.json next to the compose file (mounted read-only into
# the container). Contents:
#   - sts.signingKey: S3_STS_SIGNING_KEY from .env (generated + appended on
#     first run; rotating it only invalidates outstanding <=1h sessions)
#   - role umrs-attempt: what ADR-043 AssumeRole sessions may do at most —
#     object read/write/delete inside S3_BUCKET; the per-attempt inline
#     session policy narrows that to the attempt's prefixes. s3:ListBucket is
#     deliberately absent: SeaweedFS 4.47 ignored the s3:prefix condition on
#     ListBucket in session policies (ADR-055 § Verification), so allowing it
#     here would let a session enumerate keys outside its scope.
#   - trust policy pinned to the admin principal SeaweedFS derives from the
#     env-bootstrapped identity ("admin-" + first 8 chars of the access key),
#     so per-user identities cannot assume the role (verified 2026-09-14).
_render_seaweedfs_iam_config() {
    local dir="${SCRIPT_DIR}/seaweedfs" principal bucket
    if [[ -z "${S3_STS_SIGNING_KEY:-}" ]]; then
        S3_STS_SIGNING_KEY="$(head -c 32 /dev/urandom | base64 -w0)"
        printf '\n# SeaweedFS STS token signing key (ADR-055); generated by start.sh\nS3_STS_SIGNING_KEY=%s\n' "$S3_STS_SIGNING_KEY" >> "${SCRIPT_DIR}/.env"
        echo "  Generated S3_STS_SIGNING_KEY into .env"
    fi
    export S3_STS_SIGNING_KEY
    principal="admin-${S3_ROOT_USER:0:8}"
    bucket="${S3_BUCKET}"
    # Directory 0700 keeps the signing key from other host users; the FILE is
    # 0644 because the image runs weed as a non-root user and podman bind-
    # mounts the file directly (run 34834502286: "open /etc/seaweedfs/iam.json:
    # permission denied" with a 0600 file).
    mkdir -p "$dir" && chmod 700 "$dir"
    ( umask 022; cat > "${dir}/iam.json" <<EOF_IAM
{
  "sts": {
    "tokenDuration": "1h",
    "maxSessionLength": "1h",
    "issuer": "umrs-sts",
    "signingKey": "${S3_STS_SIGNING_KEY}"
  },
  "policies": [
    {
      "name": "UmrsAttemptRoleBase",
      "document": {
        "Version": "2012-10-17",
        "Statement": [
          {
            "Effect": "Allow",
            "Action": ["s3:GetObject", "s3:PutObject", "s3:DeleteObject", "s3:GetBucketLocation"],
            "Resource": ["arn:aws:s3:::${bucket}", "arn:aws:s3:::${bucket}/*"]
          }
        ]
      }
    }
  ],
  "roles": [
    {
      "roleName": "umrs-attempt",
      "roleArn": "arn:aws:iam::role/umrs-attempt",
      "attachedPolicies": ["UmrsAttemptRoleBase"],
      "trustPolicy": {
        "Version": "2012-10-17",
        "Statement": [
          {
            "Effect": "Allow",
            "Principal": {"AWS": "arn:aws:iam::000000000000:user/${principal}"},
            "Action": ["sts:AssumeRole"]
          }
        ]
      }
    }
  ]
}
EOF_IAM
    )
    # `cat >` keeps the mode of a pre-existing file (0600 from earlier renders,
    # run 34835109970) — set it explicitly.
    chmod 644 "${dir}/iam.json"
    # SELinux: the compose bind of a single file did not get the :z relabel on
    # data0 (weed: "open /etc/seaweedfs/iam.json: permission denied" while the
    # :z-mounted /data volume worked). Apply the shared container label
    # ourselves — the same label podman applies for :z. No-op where SELinux is
    # absent or disabled.
    if command -v chcon >/dev/null 2>&1 && [[ "$(getenforce 2>/dev/null || echo Disabled)" != "Disabled" ]]; then
        chcon -R -t container_file_t -l s0 "$dir" 2>/dev/null \
            && echo "  Relabelled ${dir} as container_file_t (SELinux $(getenforce))" \
            || echo "  WARNING: could not relabel ${dir} for containers (SELinux $(getenforce))"
    fi
    echo "  Rendered ${dir}/iam.json (STS role umrs-attempt, trust -> ${principal})"
}

# ─── Ensure rootless Podman socket is available ──────────────────────────────
# Non-interactive SSH sessions (Ansible) don't set XDG_RUNTIME_DIR and the
# Podman user socket may not be running.  podman compose delegates to the
# docker-compose plugin which requires the API socket.
if [[ -z "${XDG_RUNTIME_DIR:-}" ]]; then
    export XDG_RUNTIME_DIR="/run/user/$(id -u)"
fi
mkdir -p "$XDG_RUNTIME_DIR" 2>/dev/null || true
# `.Path` is always printed; `.Exists` says whether the socket is actually there.
if [[ "$(podman info --format '{{.Host.RemoteSocket.Exists}}' 2>/dev/null)" != "true" ]]; then
    echo "Starting rootless Podman socket..."
    systemctl --user start podman.socket 2>/dev/null || true
fi

# ─── Load .env ───────────────────────────────────────────────────────────────
if [[ ! -f .env ]]; then
    echo "ERROR: .env not found. Create from template in setup.sh"
    exit 1
fi
ENV_UMRS_SERVER_HOST="${UMRS_SERVER_HOST:-}"
ENV_UMRS_ADVERTISE_HOST="${UMRS_ADVERTISE_HOST:-}"
ENV_S3_ENDPOINT_URL="${S3_ENDPOINT_URL:-}"
ENV_S3_BUCKET="${S3_BUCKET:-}"
set -o allexport
source .env
set +o allexport
[[ -n "$ENV_UMRS_SERVER_HOST" ]] && UMRS_SERVER_HOST="$ENV_UMRS_SERVER_HOST"
[[ -n "$ENV_UMRS_ADVERTISE_HOST" ]] && UMRS_ADVERTISE_HOST="$ENV_UMRS_ADVERTISE_HOST"
[[ -n "$ENV_S3_ENDPOINT_URL" ]] && S3_ENDPOINT_URL="$ENV_S3_ENDPOINT_URL"
[[ -n "$ENV_S3_BUCKET" ]] && S3_BUCKET="$ENV_S3_BUCKET"

# ─── Object store settings (ADR-055: SeaweedFS; MINIO_* names accepted as legacy) ──
# S3_ROOT_USER/S3_ROOT_PASSWORD bootstrap the SeaweedFS admin identity. Older
# .env files carry them as MINIO_ROOT_USER/MINIO_ROOT_PASSWORD — honoured here
# so a not-yet-migrated .env still starts; Ansible persists the S3_* names.
export S3_ROOT_USER="${S3_ROOT_USER:-${MINIO_ROOT_USER:-}}"
export S3_ROOT_PASSWORD="${S3_ROOT_PASSWORD:-${MINIO_ROOT_PASSWORD:-}}"
[[ -n "$S3_ROOT_USER" && -n "$S3_ROOT_PASSWORD" ]] || { echo "ERROR: S3_ROOT_USER / S3_ROOT_PASSWORD must be set in .env"; exit 1; }
export S3_PORT="${S3_PORT:-${MINIO_PORT:-9000}}"
export S3_BIND="${S3_BIND:-${MINIO_BIND:-0.0.0.0}}"
export S3_IAM_PORT="${S3_IAM_PORT:-8111}"
export S3_METRICS_PORT="${S3_METRICS_PORT:-9327}"
export S3_METRICS_BIND="${S3_METRICS_BIND:-0.0.0.0}"
export S3_BACKEND="${S3_BACKEND:-seaweedfs}"
export S3_IMAGE="${S3_IMAGE:-docker.io/chrislusf/seaweedfs:4.47}"
export S3_BUCKET="${S3_BUCKET:-r4-data}"
if [[ "$S3_BIND" == "0.0.0.0" || "$S3_BIND" == "::" ]]; then
    echo "WARNING: S3 API will bind to ${S3_BIND}:${S3_PORT}; ensure host/firewall access is restricted to trusted cluster paths."
fi

mkdir -p "$LOG_DIR"

UMRS_RCCS_ZMQ_PORT="${UMRS_RCCS_ZMQ_PORT:-50090}"
UMRS_RCCS_DATA_PORT_RANGE="${UMRS_RCCS_DATA_PORT_RANGE:-50091-50098}"
UMRS_AI4S_ZMQ_PORT="${UMRS_AI4S_ZMQ_PORT:-50100}"
UMRS_AI4S_DATA_PORT_RANGE="${UMRS_AI4S_DATA_PORT_RANGE:-50101-50108}"
UMRS_BDRT_ZMQ_PORT="${UMRS_BDRT_ZMQ_PORT:-50110}"
UMRS_BDRT_DATA_PORT_RANGE="${UMRS_BDRT_DATA_PORT_RANGE:-50111-50118}"
UMRS_OCTOPUS_ZMQ_PORT="${UMRS_OCTOPUS_ZMQ_PORT:-50120}"
UMRS_OCTOPUS_DATA_PORT_RANGE="${UMRS_OCTOPUS_DATA_PORT_RANGE:-50121-50128}"
UMRS_ZMQ_AUTH_TYPE="${UMRS_ZMQ_AUTH_TYPE:-none}"

# ─── Start infrastructure containers ─────────────────────────────────────────
if [[ "$START_MODE" != "--server" ]]; then
    echo "Starting infrastructure containers via podman compose..."

    # Check for port conflicts before starting
    _pg_port="${POSTGRES_PORT:-5432}"
    if ss -tlnp 2>/dev/null | grep -q ":${_pg_port}\b"; then
        if ! podman inspect umrs-postgres >/dev/null 2>&1 || \
           [[ "$(podman inspect -f '{{.State.Status}}' umrs-postgres 2>/dev/null)" != "running" ]]; then
            echo "  WARNING: Port ${_pg_port} is occupied by another process (native postgres?)."
            echo "           Attempting to use it — if UMRS fails to connect, stop the native"
            echo "           postgres and re-run:  sudo systemctl stop postgresql"
        fi
    fi

    # Ensure named volumes exist (compose uses external: true).
    #
    # UMRS_VOLUME_ROOT relocates the persistent data off the podman graphroot
    # (which lives under $HOME) and onto a dedicated filesystem. On umrs-front
    # the root fs is shared with the container image store — which is by far
    # the largest consumer — while S3 object storage grows without bound, so
    # keeping both on the same volume eventually starves the database.
    #
    # When set, the volumes are created as bind-backed local volumes pointing
    # at $UMRS_VOLUME_ROOT/<name>. The directory must already exist and be
    # writable by this user, and on SELinux hosts it must carry a
    # container-writable label:
    #   sudo semanage fcontext -a -e /home /share/umrs
    #   sudo restorecon -Rv /share/umrs
    #
    # We deliberately fail instead of falling back to the graphroot: a stack
    # that silently writes the database somewhere other than the operator
    # intended is worse than a stack that refuses to start.
    _ensure_volume() {
        local name="$1"
        if podman volume inspect "$name" >/dev/null 2>&1; then
            return 0
        fi
        if [[ -z "${UMRS_VOLUME_ROOT:-}" ]]; then
            podman volume create "$name"
            return 0
        fi
        local dir="${UMRS_VOLUME_ROOT%/}/${name}"
        if [[ ! -d "$dir" ]]; then
            echo "ERROR: UMRS_VOLUME_ROOT is set but '$dir' does not exist." >&2
            echo "       Create and label it before starting (see comment above)." >&2
            return 1
        fi
        if [[ ! -w "$dir" ]]; then
            echo "ERROR: '$dir' is not writable by $(whoami)." >&2
            return 1
        fi
        echo "  Creating volume $name backed by $dir"
        podman volume create --driver local \
            --opt type=none --opt o=bind --opt device="$dir" "$name"
    }

    _ensure_volume umrs_pg_data
    _ensure_volume umrs_s3_data

    # SeaweedFS IAM config (STS role + signing key + admin principal), rendered
    # from .env so a root-credential rotation re-pins the trust policy.
    _render_seaweedfs_iam_config

    # Remove legacy containers that conflict with compose-managed names.
    # umrs-minio is the pre-ADR-055 object store: stopped here for good; its
    # volume (umrs_minio_data) is left in place for the operator to remove.
    # The compose provider records depends_on as podman dependencies: the
    # UMRS server containers depend on postgres and the object store, and
    # mcp-apps on the servers. Removing an infrastructure container while a
    # dependent exists fails ("has dependent containers"), and `rm --depend`
    # proved racy against the dependents' own stop (2026-09-14 cutover, ADR-055).
    # So: remove dependents first, explicitly, in reverse dependency order.
    # All of them are recreated by the `compose up` calls later in this script.
    for _ctr in umrs-mcp-apps umrs-server-rccs umrs-server-ai4s umrs-server-bdrt umrs-server-octopus umrs-server; do
        if podman inspect "$_ctr" >/dev/null 2>&1; then
            echo "  Removing dependent container $_ctr (recreated later)..."
            podman stop -t 10 "$_ctr" 2>/dev/null || true
            # --ignore: a record whose storage is already gone must not block
            # the recreate (2026-09-14 recovery).
            podman rm -f --ignore "$_ctr" || echo "  WARNING: podman rm $_ctr failed (see above)"
        fi
    done
    for _ctr in umrs-postgres umrs-seaweedfs umrs-minio; do
        if podman inspect "$_ctr" >/dev/null 2>&1; then
            echo "  Removing legacy container $_ctr (and dependents)..."
            podman stop "$_ctr" 2>/dev/null || true
            podman rm -f --depend --ignore "$_ctr" || echo "  WARNING: podman rm --depend $_ctr failed (see above)"
        fi
        # A compose create that failed half-way leaves a storage-only entry
        # (invisible to `podman ps -a`, listed by --external) that keeps the
        # name reserved: "container name X is already in use by <id>"
        # (2026-09-14 cutover, ADR-055). Data lives in the bind-backed volumes,
        # so dropping these rw layers is safe.
        # Full IDs (--no-trunc): storage-container lookups are exact-match.
        # `ps -a --external` lists regular containers TOO; only entries whose
        # status is "Storage" are the leaked storage-only ones.
        for _sid in $(podman ps -a --external --no-trunc --filter "name=^${_ctr}\$" --format '{{.ID}} {{.Status}}' 2>/dev/null | awk '$2 == "Storage" {print $1}'); do
            echo "  Removing leaked storage entry for $_ctr ($_sid)..."
            if ! podman rm -f --storage "$_sid"; then
                echo "  WARNING: podman rm --storage $_sid failed; retrying by name..."
                podman rm -f --storage "$_ctr" || echo "  WARNING: leaked storage entry for $_ctr still present"
            fi
        done
    done

    podman compose -f "${SCRIPT_DIR}/docker-compose.yaml" up -d postgres seaweedfs

    # Wait for postgres
    echo -n "  Waiting for postgres..."
    for i in $(seq 1 30); do
        if pg_isready -h 127.0.0.1 -p "${POSTGRES_PORT:-5432}" -U "${POSTGRES_USER:-umrs}" >/dev/null 2>&1 || \
           podman exec umrs-postgres pg_isready -h localhost -U "${POSTGRES_USER:-umrs}" >/dev/null 2>&1 || \
           bash -c "echo >/dev/tcp/127.0.0.1/${POSTGRES_PORT:-5432}" 2>/dev/null; then
            echo " ready."
            break
        fi
        echo -n "."
        sleep 1
        [[ "$i" -eq 30 ]] && echo " WARNING: postgres not ready after 30s"
    done

    # Create AI4S database if it doesn't exist (container-first)
    _pg_cmd() { podman exec umrs-postgres psql -U "${POSTGRES_USER:-umrs}" "$@" 2>/dev/null || \
                PGPASSWORD="${POSTGRES_PASSWORD}" psql -h 127.0.0.1 -p "${POSTGRES_PORT:-5432}" -U "${POSTGRES_USER:-umrs}" "$@" 2>/dev/null; }
    _pg_cmd -d postgres -tc "SELECT 1 FROM pg_database WHERE datname='${POSTGRES_DB_AI4S:-umrs_ai4s}'" \
        | grep -q 1 || \
    _pg_cmd -d postgres -c "CREATE DATABASE ${POSTGRES_DB_AI4S:-umrs_ai4s};" || true

    # Create bdrt database if it doesn't exist (container-first)
    _pg_cmd -d postgres -tc "SELECT 1 FROM pg_database WHERE datname='${POSTGRES_DB_BDRT:-front_bdrt}'" \
        | grep -q 1 || \
    _pg_cmd -d postgres -c "CREATE DATABASE ${POSTGRES_DB_BDRT:-front_bdrt};" || true

    # Create octopus database if it doesn't exist (container-first)
    _pg_cmd -d postgres -tc "SELECT 1 FROM pg_database WHERE datname='${POSTGRES_DB_OCTOPUS:-front_octopus}'" \
        | grep -q 1 || \
    _pg_cmd -d postgres -c "CREATE DATABASE ${POSTGRES_DB_OCTOPUS:-front_octopus};" || true

    # Ensure pgvector extension in all databases
    for db in "${POSTGRES_DB_RCCS:-front_rccs}" "${POSTGRES_DB_AI4S:-front_ai4s}" "${POSTGRES_DB_BDRT:-front_bdrt}" "${POSTGRES_DB_OCTOPUS:-front_octopus}"; do
        _pg_cmd -d "$db" -c "CREATE EXTENSION IF NOT EXISTS vector;" || true
    done

    # Wait for the S3 API (SeaweedFS answers /status). Everything after this
    # point (bucket bootstrap, servers) needs it, so a store that never comes
    # up is fatal — with the container state and logs printed first so the
    # converge log carries the reason (2026-09-14 cutover, ADR-055).
    echo -n "  Waiting for seaweedfs..."
    _s3_ready=0
    for i in $(seq 1 180); do
        if curl -sf "http://127.0.0.1:${S3_PORT}/status" >/dev/null 2>&1; then
            echo " ready (${i}s)."
            _s3_ready=1
            break
        fi
        echo -n "."
        sleep 1
    done
    if [[ "$_s3_ready" -ne 1 ]]; then
        echo " ERROR: seaweedfs not ready after 180s. Diagnostics:"
        echo "  selinux: $(getenforce 2>/dev/null || echo n/a); iam.json: $(ls -lZ "${SCRIPT_DIR}/seaweedfs/iam.json" 2>/dev/null || echo missing)"
        podman ps -a --filter name=umrs-seaweedfs --format '  container: {{.Names}} {{.Status}} ports={{.Ports}}' 2>&1 || true
        podman inspect -f '  state: {{.State.Status}} exit={{.State.ExitCode}} restarts={{.RestartCount}} started={{.State.StartedAt}} error={{.State.Error}}' umrs-seaweedfs 2>&1 || true
        echo "  --- podman logs umrs-seaweedfs (fatal/error/startup lines) ---"
        podman logs umrs-seaweedfs 2>&1 | grep -E '^(F|E)[0-9]|Start Seaweed|listening|panic|fatal|error' | tail -60 | sed 's/^/  | /' || true
        echo "  --- podman logs --tail 25 umrs-seaweedfs ---"
        podman logs --tail 25 umrs-seaweedfs 2>&1 | sed 's/^/  | /' || true
        echo "  --- listeners on :${S3_PORT} ---"
        (ss -ltnp 2>/dev/null || netstat -ltnp 2>/dev/null) | grep ":${S3_PORT} " | sed 's/^/  | /' || echo "  | (none)"
        exit 1
    fi
fi

# ─── Build UMRS server image (needed for utility tasks and servers) ──────────
echo "Ensuring UMRS server image is available..."
if [[ "${UMRS_IMAGE_REBUILD:-false}" == "true" ]] || \
   ! podman image exists "$UMRS_IMAGE" 2>/dev/null; then
    echo "  Building UMRS server image..."
    podman compose -f "${SCRIPT_DIR}/docker-compose.yaml" build umrs-server-rccs
fi

# Helper: run a one-shot Python snippet inside the UMRS server image.
# Mounts current dir at /work and uses host networking for DB/S3 access.
_run_util() {
    podman run --rm --network=host \
        -v "${SCRIPT_DIR}:/work:z" \
        -v "${HOME}/.config/umrs:/root/.config/umrs:z" \
        -w /work \
        -e S3_ENDPOINT_URL -e S3_ACCESS_KEY -e S3_SECRET_KEY \
        -e S3_REGION -e S3_BUCKET -e S3_USE_SSL -e S3_BACKEND -e S3_IAM_ENDPOINT_URL \
        -e S3_ROOT_USER -e S3_ROOT_PASSWORD \
        -e S3_PORT -e POSTGRES_USER -e POSTGRES_PASSWORD \
        -e POSTGRES_PORT -e POSTGRES_DB_RCCS -e POSTGRES_DB_AI4S -e POSTGRES_DB_BDRT -e POSTGRES_DB_OCTOPUS \
        "$UMRS_IMAGE" python -c "$1"
}

# ─── Set env vars for utility tasks ──────────────────────────────────────────
export PYTHONUNBUFFERED=1
export UMRS_AUTH_MODE="${UMRS_AUTH_MODE:-strict}"
export S3_ENDPOINT_URL="${S3_ENDPOINT_URL:-http://127.0.0.1:${S3_PORT}}"
export S3_IAM_ENDPOINT_URL="${S3_IAM_ENDPOINT_URL:-http://127.0.0.1:${S3_IAM_PORT}}"
export S3_ACCESS_KEY="${S3_ACCESS_KEY:-${S3_ROOT_USER}}"
export S3_SECRET_KEY="${S3_SECRET_KEY:-${S3_ROOT_PASSWORD}}"
export S3_REGION="${S3_REGION:-us-east-1}"
export S3_USE_SSL="${S3_USE_SSL:-false}"

# Generate persisted server CURVE keys when ZMQ CURVE/session auth is enabled.
# Session mode uses these server keys plus an in-memory ZAP credential provider;
# it does not use a static client key directory.
if [[ "$UMRS_ZMQ_AUTH_TYPE" == "curve" || "$UMRS_ZMQ_AUTH_TYPE" == "session" ]]; then
    ZMQ_CURVE_SERVER_KEYS_DIR="${UMRS_ZMQ_CURVE_SERVER_KEYS_DIR:-${HOME}/.config/umrs/curve-keys/server}"
    mkdir -p "$ZMQ_CURVE_SERVER_KEYS_DIR"
    chmod 700 "$ZMQ_CURVE_SERVER_KEYS_DIR"

    if [[ -z "${UMRS_ZMQ_CURVE_SERVER_PUBLIC_KEY:-}" && -z "${UMRS_ZMQ_CURVE_SERVER_PUBLIC_KEY_FILE:-}" ]] || \
       [[ -z "${UMRS_ZMQ_CURVE_SERVER_SECRET_KEY:-}" && -z "${UMRS_ZMQ_CURVE_SERVER_SECRET_KEY_FILE:-}" ]]; then
        _run_util "
import zmq
from pathlib import Path

key_dir = Path('/root/.config/umrs/curve-keys/server')
key_dir.mkdir(parents=True, exist_ok=True)
public_path = key_dir / 'server.key'
secret_path = key_dir / 'server.key_secret'

if not public_path.exists() or not secret_path.exists():
    public_key, secret_key = zmq.curve_keypair()
    public_path.write_text(public_key.decode('ascii') + '\n', encoding='utf-8')
    secret_path.write_text(secret_key.decode('ascii') + '\n', encoding='utf-8')

public_path.chmod(0o600)
secret_path.chmod(0o600)
"
    fi

    if [[ -z "${UMRS_ZMQ_CURVE_SERVER_PUBLIC_KEY:-}" && -z "${UMRS_ZMQ_CURVE_SERVER_PUBLIC_KEY_FILE:-}" ]]; then
        export UMRS_ZMQ_CURVE_SERVER_PUBLIC_KEY_FILE="$ZMQ_CURVE_SERVER_KEYS_DIR/server.key"
    fi
    if [[ -z "${UMRS_ZMQ_CURVE_SERVER_SECRET_KEY:-}" && -z "${UMRS_ZMQ_CURVE_SERVER_SECRET_KEY_FILE:-}" ]]; then
        export UMRS_ZMQ_CURVE_SERVER_SECRET_KEY_FILE="$ZMQ_CURVE_SERVER_KEYS_DIR/server.key_secret"
    fi
fi

_run_util "
import os
import boto3
from botocore.config import Config as BotoConfig
from botocore.exceptions import ClientError

bucket = os.environ['S3_BUCKET']
s3 = boto3.client(
    's3',
    endpoint_url=os.environ['S3_ENDPOINT_URL'],
    aws_access_key_id=os.environ['S3_ACCESS_KEY'],
    aws_secret_access_key=os.environ['S3_SECRET_KEY'],
    region_name=os.environ.get('S3_REGION', 'us-east-1'),
    config=BotoConfig(signature_version='s3v4', s3={'addressing_style': 'path'}),
    use_ssl=os.environ.get('S3_USE_SSL', 'false').lower() == 'true',
    verify=os.environ.get('S3_USE_SSL', 'false').lower() == 'true',
)
try:
    s3.head_bucket(Bucket=bucket)
except ClientError as exc:
    code = exc.response.get('Error', {}).get('Code')
    if code not in {'404', 'NoSuchBucket'}:
        raise
    s3.create_bucket(Bucket=bucket)
"

# ─── Create s3cfg for admin ──────────────────────────────────────────────────
S3CFG="${SCRIPT_DIR}/s3cfg"
if [[ ! -f "$S3CFG" ]]; then
    cat > "$S3CFG" <<EOF
[default]
access_key = ${S3_ROOT_USER}
secret_key = ${S3_ROOT_PASSWORD}
host_base = 127.0.0.1:${S3_PORT}
host_bucket = 127.0.0.1:${S3_PORT}
bucket_location = us-east-1
use_https = False
signature_v2 = False
EOF
fi

